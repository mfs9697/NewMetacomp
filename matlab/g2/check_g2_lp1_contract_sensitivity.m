function S=check_g2_lp1_contract_sensitivity()
%CHECK_G2_LP1_CONTRACT_SENSITIVITY Mutation test of the LP1 contract suite (VG1, Issue #58).
% Each case writes ONE deliberately sabotaged copy of a guarded function into a fresh
% temporary folder outside the repository, puts it first on the path, runs
% check_g2_lp1_contract(false) and requires that (i) the suite fails overall and
% (ii) every named detecting test fails. The original sources are never modified;
% the temporary folder is removed from the path afterwards. No mesh, FEM or GO.
here=fileparts(mfilename('fullpath'));
cases={ ...
 'token_binding_removed','g2_lp1_go_validate.m', ...
   '&& ...\n strcmp(G.approvedToken,C.token), ...',', ...',{'go_token_mismatch'}; ...
 'binding_identifier_wrong','g2_lp1_go_validate.m', ...
   '''G2LP1:HOLD_SOURCE'',''Scientific GO does not bind','''G2LP1:HOLD_UNAUTHORIZED_STATE'',''Scientific GO does not bind', ...
   {'go_policy_mismatch','go_source_mismatch','go_lp0_mismatch','go_token_mismatch'}; ...
 'unrelated_same_identifier','g2_lp1_go_validate.m', ...
   'fields={','error(''G2LP1:HOLD_SOURCE'',''unrelated failure'');fields={', ...
   {'go_fixture_positive_control','go_policy_mismatch','go_contract_missing','go_wrong_decision'}; ...
 'links_identifier_collapsed','g2_lp1_validate_links.m', ...
   '''G2LP1:HOLD_SOURCE'',''Parent/source/policy link differs.''','''G2LP1:HOLD_RECORD_INTEGRITY'',''Parent/source/policy link differs.''', ...
   {'mutate_policySHA256','mutate_sourceSHA256','mutate_parentSHA256'}; ...
 'folder_before_memory_guard','g2_lp1_admit_state.m', ...
   'assert(isnumeric(freeGiB)','mkdir(sd);assert(isnumeric(freeGiB)', ...
   {'admit_low_memory_no_folder','admit_nonfinite_no_folder'}; ...
 'S5_cap_removed','g2_lp1_forecast.m', ...
   'assert(k>=1&&k<=4&&k<=pol.caps.maxStateIndex,','assert(k>=1,', ...
   {'S5_forecast'}; ...
 'overwrite_allowed','g2_trajectory_record.m', ...
   'assert(~isfile(file)&&~isfile(manifest),','assert(true,', ...
   {'overwrite_refused'}; ...
 'absent_go_not_checked','g2_lp1_scientific_gate.m', ...
   'assert(isfile(p),','assert(true,', ...
   {'go_absent_production_gate'}};
rows=struct('mutation',{},'file',{},'applied',{},'suiteFailed',{},'detectedBy',{},'missed',{},'pass',{});
for k=1:size(cases,1)
 [name,file,from,to,need]=cases{k,:};
 from=sprintf(strrep(from,'%','%%'));to=sprintf(strrep(to,'%','%%'));
 src=fileread(fullfile(here,file));src=strrep(src,sprintf('\r\n'),sprintf('\n'));
 applied=numel(strfind(src,from))==1;
 tmp=tempname;mkdir(tmp);cleaner=onCleanup(@()cleanupTmp(tmp));
 failedNames={};suiteFailed=false;
 if applied
  fid=fopen(fullfile(tmp,file),'w');fwrite(fid,strrep(src,from,to),'char');fclose(fid);
  addpath(tmp,'-begin');clear(file(1:end-2));rehash;
  assert(strcmpi(which(file(1:end-2)),fullfile(tmp,file)),'G2LP1:HOLD_TEST','Sabotaged copy not active: %s',file);
  try
   evalc('T=check_g2_lp1_contract(false);');
   suiteFailed=~T.pass;failedNames={T.tests(~[T.tests.pass]).name};
  catch ME
   suiteFailed=true;failedNames={['<suite error> ',ME.identifier]};
  end
  rmpath(tmp);clear(file(1:end-2));rehash;
 end
 clear cleaner
 detected=intersect(need,failedNames);missed=setdiff(need,failedNames);
 rows(end+1)=struct('mutation',name,'file',file,'applied',applied,'suiteFailed',suiteFailed, ...
  'detectedBy',{detected},'missed',{missed},'pass',applied&&suiteFailed&&isempty(missed)); %#ok<AGROW>
 fprintf('MUTATION %s applied=%d suiteFailed=%d detected=%s missed=%s -> %d\n',name,applied,suiteFailed, ...
  strjoin(detected,','),strjoin(missed,','),rows(end).pass);
end
% The unmodified suite must pass again after all mutations are removed.
clean=check_g2_lp1_contract(false);
S=struct('schema','NewMetacomp.G2.LP1.ContractSensitivity.v1','mutations',rows, ...
 'detected',nnz([rows.pass]),'total',numel(rows),'cleanSuiteAfter',clean.pass, ...
 'pass',all([rows.pass])&&clean.pass,'physicalSolves',0,'meshBuilds',0);
fprintf('G2_LP1_CONTRACT_SENSITIVITY=%d/%d CLEAN_AFTER=%d\n',S.detected,S.total,clean.pass);
assert(S.pass,'G2LP1:ContractSensitivity','The contract suite missed a sabotaged guard.');
end

function cleanupTmp(tmp)
if contains(path,tmp),rmpath(tmp);end
if isfolder(tmp),rmdir(tmp,'s');end
end
