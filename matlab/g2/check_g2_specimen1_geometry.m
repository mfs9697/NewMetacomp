function ok = check_g2_specimen1_geometry()
%CHECK_G2_SPECIMEN1_GEOMETRY Read-only geometry qualification for MATLAB.
% No FEM assembly, mesh generation, physical solve, or crack propagation.
    R = build_g2_specimen1_geometry('Visible','off','Export',false);
    cleanup = onCleanup(@() close(R.figure)); %#ok<NASGU>
    assert(R.audit.pass,'Nominal coordinate audit failed.');
    assert(~R.is_FEM_ready, ...
        'A crack overlay must not be misclassified as FEM-ready geometry.');
    assert(~R.is_experiment_certified, ...
        'Exact experimental source scan has not been qualified.');
    assert(R.model.Geometry.NumFaces == 1, ...
        'Subtraction should leave exactly one connected solid face.');
    assert(R.model.Geometry.NumEdges >= 7, ...
        'Unexpectedly few geometry edges for a three-hole solid.');
    expected = (sqrt((152.4-101.6)^2 + ...
            (69.85-25.4)^2) - 6.35);
    assert(abs(R.audit.tip_clearance_mm-expected)<1e-10, ...
        'Unexpected crack tip to bottom-hole clearance.');
    assert(size(R.crack_overlay_mm,1)==2 && ...
        size(R.crack_overlay_mm,2)==2,'Crack annotation has wrong shape.');
    ok = true;
    fprintf(['PASS: geometry-only 1-face/3-hole CAD, 25.4-mm slit ', ...
        'annotation, 61.1514-mm clearance. FEM NOT tested.\n']);
end
