function G=g2_a1_go_validate(G,C,loadContract)
%G2_A1_GO_VALIDATE  Pure validation of a decoded A1 scientific GO (Issue #66). Opens no file.
% Same structure as the VG2 validator g2_lp1_go_validate, for the separate A1 scope: one named
% campaign of at most twelve fixed-geometry Family B solves (four S4 paths x m = 3, 6, 9).
% HOLD_UNAUTHORIZED_STATE: absent/invalid decision, review, scope, run name, campaign ID or
% contract qualification. HOLD_SOURCE: any policy/source/mesh-manifest/token/contract binding.
% The revoked A0 GO and the A0/LP1 run names can never satisfy this validator.
fields={'decision','reviewStatus','scientificReviewer','reviewURL','approvedA1PolicySHA256', ...
 'approvedSourceSHA256','approvedMeshManifestSHA256','approvedToken','contractEvidenceFile', ...
 'contractEvidenceSHA256','approvedRunName','campaignId','campaignScope'};
assert(isstruct(G)&&isscalar(G)&&all(isfield(G,fields)),'G2A1:HOLD_UNAUTHORIZED_STATE', ...
 'Incomplete A1 scientific GO record.');
assert(ischar(G.decision)&&strcmp(G.decision,'GO_A1_PHYSICAL')&& ...
 ischar(G.reviewStatus)&&strcmp(G.reviewStatus,'REVIEWED_ACCEPTED')&& ...
 ischar(G.scientificReviewer)&&~isempty(strtrim(G.scientificReviewer))&& ...
 ischar(G.reviewURL)&&startsWith(G.reviewURL,'https://github.com/mfs9697/NewMetacomp/'), ...
 'G2A1:HOLD_UNAUTHORIZED_STATE','A1 GO decision or review proof is absent or invalid.');
assert(ischar(G.campaignScope)&&strcmp(G.campaignScope,'A1_S4_FAMILY_B_FIXED_PATH_MAX12')&& ...
 ischar(G.approvedRunName)&&~isempty(regexp(G.approvedRunName,'^run_[a-zA-Z0-9_]+$','once'))&& ...
 ~any(strcmp(G.approvedRunName,{'run_20261122_lp1_v1','run_a0_lp1_repro_v1'}))&& ...
 ischar(G.campaignId)&&~isempty(regexp(G.campaignId,'^[A-Za-z0-9_-]{3,64}$','once'))&& ...
 ~strcmp(G.campaignId,'G2-LP1-A0-001'), ...
 'G2A1:HOLD_UNAUTHORIZED_STATE','A1 campaign scope, run name or campaign ID is invalid.');
assert(strcmpi(G.approvedA1PolicySHA256,C.policySHA256)&&strcmpi(G.approvedSourceSHA256,C.sourceSHA256)&& ...
 strcmpi(G.approvedMeshManifestSHA256,C.meshManifestSHA256)&&strcmp(G.approvedToken,C.token), ...
 'G2A1:HOLD_SOURCE','A1 GO does not bind the exact policy, source, mesh manifest and token.');
f=G.contractEvidenceFile;
assert(ischar(f)&&startsWith(f,'matlab/g2/evidence/a1_preflight/')&&isempty(strfind(f,'..'))&& ...
 ~isempty(regexp(f,'^[A-Za-z0-9_./-]+$','once')),'G2A1:HOLD_SOURCE','A1 contract evidence path is not pinned.');
E=loadContract(f);
assert(isstruct(E)&&isscalar(E)&&isfield(E,'exists')&&isequal(E.exists,true)&&ischar(E.sha256)&& ...
 ischar(G.contractEvidenceSHA256)&&strcmpi(E.sha256,G.contractEvidenceSHA256), ...
 'G2A1:HOLD_SOURCE','A1 contract evidence bytes are absent or changed.');
T=jsondecode(E.text);
need={'pass','passed','total','physicalSolves','negativeTestsPassed'};
assert(isstruct(T)&&all(isfield(T,need)),'G2A1:HOLD_UNAUTHORIZED_STATE','A1 contract evidence lacks required fields.');
assert(isequal(T.pass,true)&&T.passed==T.total&&T.total>=20&&T.physicalSolves==0&&isequal(T.negativeTestsPassed,true), ...
 'G2A1:HOLD_UNAUTHORIZED_STATE','A1 contract qualification has not passed.');
end
