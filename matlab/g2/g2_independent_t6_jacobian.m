function J = g2_independent_t6_jacobian(X6,T6)
%G2_INDEPENDENT_T6_JACOBIAN  Actual 13-point quadratic-triangle Jacobian.
% Geometry-only, independent of the PDE mesher. Input X6: N-by-2,
% T6: M-by-6 [corner1 corner2 corner3 mid12 mid23 mid31].
% IMPORTANT: T6(:) + reshape preserves M-by-6 shape for MATLAB R2023a.
% The erroneous X6(T6,1) indexing in audit v0 caused dimension mismatch.
assert(isnumeric(X6)&&isnumeric(T6)&&size(X6,2)==2&& ...
       size(T6,2)==6&&~isempty(T6), ...
       'G2Independent:JacobianShape', ...
       'Expected finite N-by-2 coordinates and nonempty M-by-6 T6.');
assert(all(isfinite(X6(:)))&&all(isfinite(T6(:)))&& ...
       all(T6(:)==round(T6(:)))&&all(T6(:)>=1)&& ...
       all(T6(:)<=size(X6,1)), ...
       'G2Independent:JacobianIndices', ...
       'T6 node IDs or coordinates invalid.');
nElem=size(T6,1);
x=reshape(X6(T6(:),1),size(T6));
y=reshape(X6(T6(:),2),size(T6));
assert(isequal(size(x),[nElem,6])&&isequal(size(y),[nElem,6]), ...
       'G2Independent:JacobianIndexing', ...
       'Coordinate gathering failed to preserve N-element-by-6 shape.');
a=X6(T6(:,2),:)-X6(T6(:,1),:);
b=X6(T6(:,3),:)-X6(T6(:,1),:);
a2=a(:,1).*b(:,2)-a(:,2).*b(:,1);
pts=[1/3,1/3;0,0;1,0;0,1;.5,0;.5,.5;0,.5; ...
     .1,.1;.8,.1;.1,.8;.45,.45;.1,.45;.45,.1];
detMin=inf;detMax=-inf;detRel=0;
for k=1:size(pts,1)
    r=pts(k,1);s=pts(k,2);t=1-r-s;
    dNr=[-(4*t-1);4*r-1;0;4*(t-r);4*s;-4*s];
    dNs=[-(4*t-1);0;4*s-1;-4*r;4*r;4*(t-s)];
    assert(size(dNr,1)==6&&size(dNs,1)==6, ...
        'G2Independent:ShapeDerivatives', ...
        'T6 function derivative must have six entries.');
    dxdr=x*dNr;dxds=x*dNs;dydr=y*dNr;dyds=y*dNs;
    jac=dxdr.*dyds-dxds.*dydr;
    detMin=min(detMin,min(jac));
    detMax=max(detMax,max(jac));
    detRel=max(detRel,max(abs(jac-a2)./max(abs(a2),eps)));
end
J=struct('minDet_mm2',detMin,'maxDet_mm2',detMax, ...
    'maxRelativeVariation',detRel,'allPositive', ...
    all(a2>0)&&detMin>0, ...
    'constantTo1e8',detRel<1e-8, ...
    'sampleCount',size(pts,1), ...
    'elementCount',nElem);
end
