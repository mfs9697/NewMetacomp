function G=g2_lp1_go_validate(G,C,loadContract)
%G2_LP1_GO_VALIDATE Pure validation of a decoded LP1 scientific GO structure (VG1, Issue #58).
% G            decoded GO structure (in production: the hard-coded
%              matlab/g2/G2_LP1_SCIENTIFIC_GO_v1.json read by g2_lp1_scientific_gate).
% C            context with policySHA256, sourceSHA256, token, policy.lp0Evidence.sha256.
% loadContract function handle f -> struct('exists',L,'sha256',S,'text',T) for the
%              relative contract-evidence path f, called only AFTER f has been confined
%              to matlab/g2/evidence/lp1_preflight/ below. The production gate passes a
%              fixed repository reader; contract tests pass in-memory synthetic fixtures.
% This function opens no file and accepts no GO path. Failure identifiers and check
% order are identical to the PR #55 gate: HOLD_UNAUTHORIZED_STATE for absent or invalid
% decision/review/contract qualification, HOLD_SOURCE for any SHA/token/path binding.
fields={'decision','reviewStatus','scientificReviewer','reviewURL', ...
 'approvedPolicySHA256','approvedSourceSHA256','approvedLP0SHA256', ...
 'approvedToken','contractEvidenceFile','contractEvidenceSHA256'};
assert(isstruct(G)&&isscalar(G)&&all(isfield(G,fields)),'G2LP1:HOLD_UNAUTHORIZED_STATE', ...
 'Incomplete scientific GO record.');
assert(ischar(G.decision)&&strcmp(G.decision,'GO_LP1_PHYSICAL')&& ...
 ischar(G.reviewStatus)&&strcmp(G.reviewStatus,'REVIEWED_ACCEPTED')&& ...
 ischar(G.scientificReviewer)&&~isempty(strtrim(G.scientificReviewer))&& ...
 ischar(G.reviewURL)&&startsWith(G.reviewURL,'https://github.com/mfs9697/NewMetacomp/'), ...
 'G2LP1:HOLD_UNAUTHORIZED_STATE','Scientific GO/review proof is absent or invalid.');
assert(strcmpi(G.approvedPolicySHA256,C.policySHA256)&& ...
 strcmpi(G.approvedSourceSHA256,C.sourceSHA256)&& ...
 strcmpi(G.approvedLP0SHA256,C.policy.lp0Evidence.sha256)&& ...
 strcmp(G.approvedToken,C.token), ...
 'G2LP1:HOLD_SOURCE','Scientific GO does not bind exact policy/source/LP0/caps token.');
f=G.contractEvidenceFile;
assert(ischar(f)&&startsWith(f,'matlab/g2/evidence/lp1_preflight/')&& ...
 isempty(strfind(f,'..'))&&~isempty(regexp(f,'^[A-Za-z0-9_./-]+$','once')), ...
 'G2LP1:HOLD_SOURCE','Contract evidence path is not pinned to the preflight folder.');
E=loadContract(f);
assert(isstruct(E)&&isscalar(E)&&isfield(E,'exists')&&isequal(E.exists,true)&& ...
 ischar(E.sha256)&&ischar(G.contractEvidenceSHA256)&&strcmpi(E.sha256,G.contractEvidenceSHA256), ...
 'G2LP1:HOLD_SOURCE','Contract evidence bytes are absent or changed.');
T=jsondecode(E.text);
needed={'pass','passed','total','physicalSolves','meshBuilds','negativeTestsPassed','recordIntegrityPassed'};
assert(isstruct(T)&&all(isfield(T,needed)),'G2LP1:HOLD_UNAUTHORIZED_STATE', ...
 'Contract evidence lacks negative and integrity verification.');
assert(isequal(T.pass,true)&&T.passed==T.total&&T.total>=20&& ...
 T.physicalSolves==0&&T.meshBuilds==0&& ...
 isequal(T.negativeTestsPassed,true)&&isequal(T.recordIntegrityPassed,true), ...
 'G2LP1:HOLD_UNAUTHORIZED_STATE','LP1 contract qualification has not passed.');
end
