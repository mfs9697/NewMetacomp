function g2_lp1_validate_links(R,S,c,k,poly,t,ps,ss,parentHash)
% Independent semantic cross-links, in addition to immutable MAT byte hashes.
assert(R.stateIndex==k&&strcmp(R.caseId,c.id)&&isequal(R.mask,reshape(c.mask,1,3))&&R.ratio==c.ratio, ...
 'G2LP1:HOLD_RECORD_INTEGRITY','Case, mask, ratio or index changed.');
assert(strcmp(R.policySHA256,ps)&&strcmp(R.sourceSHA256,ss)&&strcmp(R.parentSHA256,parentHash), ...
 'G2LP1:HOLD_SOURCE','Parent/source/policy link differs.');
assert(isequal(R.polyline_mm,poly)&&isequal(R.tangent,t)&&R.arc_mm<=41.4+1e-9&&k<=4, ...
 'G2LP1:HOLD_RECORD_INTEGRITY','Saved geometry differs from own-parent MTS forecast.');
assert(S.K.pass&&all(cell2mat(struct2cell(S.K.criteria)))&& ...
 R.KI==S.K.KI&&R.KII==S.K.KII&&S.K.KI==S.K.EDI_all(1,1)&&S.K.KII==S.K.EDI_all(1,2)&& ...
 isequal(R.EDI_all,S.K.EDI_all)&&strcmp(S.caseId,c.id)&&strcmp(S.meshSHA256,R.meshSHA256)&& ...
 strcmp(S.phaseSHA256,R.phaseSHA256)&&strcmp(S.policySHA256,ps)&&strcmp(S.sourceSHA256,ss), ...
 'G2LP1:HOLD_RECORD_INTEGRITY','Signed K or solution/phase/mesh link differs.');
assert(S.K.KI_MPa_sqrt_m_per_kN==S.K.KI*sqrt(1000)&&S.K.KII_MPa_sqrt_m_per_kN==S.K.KII*sqrt(1000), ...
 'G2LP1:HOLD_RECORD_INTEGRITY','Unit conversion changed.');
end
