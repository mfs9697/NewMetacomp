function R=g2_p010_cornell_regular_block(varargin)
%G2_P010_CORNELL_REGULAR_BLOCK Frozen p010 + 0.3mm collar at Cornell tip.
% Geometry only, dimensions in mm except upstream frozen P0 call in meters.
% No PDE, physical FEM, stress/EDI/COD, LEFM or crack propagation.
%
% The 6 original upstream source files are byte-identical under
% vendor_p010_a14d8872 and required ON THE MATLAB PATH. The original local
% 15 source checks use an OLD two-hole 300x400mm plate: they DO NOT qualify
% this Cornell specimen. Additional mandatory Cornell three-hole checks
% are computed from the source JSON below.
here=fileparts(mfilename('fullpath'));
root=fileparts(fileparts(here));
jsonFile=fullfile(root,'docs','research','crack-growth-gaps-2026', ...
   'G2_SPECIMEN1_1990_GEOMETRY.json');
ip=inputParser;
addParameter(ip,'JsonPath',jsonFile,@(v)ischar(v)||isstring(v));
addParameter(ip,'Plot',false,@(v)islogical(v)&&isscalar(v));
parse(ip,varargin{:});o=ip.Results;
R=struct('pass',false,'stage','HOLD_NOT_STARTED', ...
 'geometryOnly',true,'approvedForLEFM',false, ...
 'p010LocalSourceKernelQualified',false, ...
 'p010CornellPlacementQualified',false, ...
 'p010GlobalProtectedMeshQualified',false, ...
 'physicalSolvePerformed',false,'gates',struct(), ...
 'failedGates',{{}},'summary',struct(),'message','');
assert(isfile(char(o.JsonPath)),'G2P010:MissingSourceJSON', ...
 'Original Cornell specimen geometry JSON missing: %s',char(o.JsonPath));
J=jsondecode(fileread(char(o.JsonPath)));
assert(strcmp(J.schema, ...
 'NewMetacomp.G2.IngraffeaGrigoriu1990.Specimen1.nominal.v1'), ...
 'G2P010:WrongSchema','Wrong Cornell nominal geometry schema.');
G=J.nominal_geometry_mm;
assert(numel(G.holes)==3,'G2P010:ThreeHoles', ...
 'Expected exactly 3 original physical Cornell holes.');
mouth=G.initial_crack.mouth(:).';
tip=G.initial_crack.tip(:).';
assert(norm(tip-[101.6,25.4])<1e-10 && ...
    norm(mouth-[101.6,0])<1e-10, ...
 'G2P010:SourceTipChanged','Frozen Cornell #1 starter tip has changed.');
delta=4;rc=3;dr=.30;ro=rc+dr;
prev=tip-[0,delta]; % 4 mm INSIDE existing starter crack: NOT a growth step
Pprior_m=[mouth;prev]/1000;
vendor=fullfile(here,'vendor_p010_a14d8872');
assert(isfile(fullfile(vendor,'main_m1i_increment_ring_geometry_only.m')), ...
 'G2P010:NoVendor','Pinned p010 vendor MATLAB source missing.');
% The launcher adds ONLY this pinned vendor directory. Never genpath a
% personal historical source with different same-name functions.
[~,L]=evalc(['main_m1i_increment_ring_geometry_only(' ...
 '''PriorCrackPolyline_m'',Pprior_m,' ...
 '''Delta_mm'',delta,''Turn_deg'',0,''Plot'',false)']);
localGates=L.gates;
local15=isa(localGates,'struct')&& ...
 numel(fieldnames(localGates))==15&& ...
 all(cell2mat(struct2cell(localGates)));
R.p010LocalSourceKernelQualified=local15;
R.summary.upstreamSourceLocalGates=nnz(cell2mat(struct2cell(localGates)));
R.summary.upstreamSourceLocalGatesTotal=numel(fieldnames(localGates));
fprintf('G2_P010_UPSTREAM_LOCAL_GATES=%d/%d\n', ...
 R.summary.upstreamSourceLocalGates, ...
 R.summary.upstreamSourceLocalGatesTotal);
if ~local15
 R.stage='HOLD_UPSTREAM_P010_KERNEL';
 R.message='Pinned original source 15-gate p010 kernel failed.';
 return
end
% Original local kernel must match source's frozen 2,788-cell/64-sector
% ring and physical positioning exactly, not merely pass legacy old plate.
Xu=1000*L.coord3;Tu=L.connect3;
t=[0 1];n=[-1 0];
phi=(0:63)'*2*pi/64;
ring=L.sourcePatch.originalAnnulus.rings{end}(:);
dn=L.sourcePatch.lowerFaceNodes(:);
[~,kD]=min(vecnorm(Xu(dn,:)-(tip-rc*t),2,2));
lowerEntry=dn(kD);
sourceFixed=numel(ring)==64 && ...
 size(Tu,1)==2788 && ...
 size(Xu,2)==2 && size(Tu,2)==3 && ...
 abs(L.summary.coreRadius_mm-rc)<1e-10 && ...
 abs(L.summary.ediInner_mm-.4)<1e-10 && ...
 abs(L.summary.ediOuter_mm-2.6)<1e-10 && ...
 norm(L.tip_m*1000-tip)<1e-9;
idealInner=tip+rc*(cos(phi)*t+sin(phi)*n);
innerAgreement=max(vecnorm(Xu(ring,:)-idealInner,2,2));
entryAgreement=norm(Xu(lowerEntry,:)-(tip-rc*t));
sourceFixed=sourceFixed && innerAgreement<1e-8 && ...
 entryAgreement<1e-8 && lowerEntry~=ring(33);
if ~sourceFixed
 R.stage='HOLD_SOURCE_P010_REGULAR_PATTERN';
 R.message='Frozen 2788-cell p010 coordinates/entry do not match the Cornell frame.';
 return
end

% Cornell-specific independent geometry, NOT copied source 2-hole gates.
bounds=[G.plate.x_range(:).',G.plate.y_range(:).'];
xmin=bounds(1);xmax=bounds(2);
ymin=bounds(3);ymax=bounds(4);
centers=zeros(3,2);radii=zeros(3,1);
for k=1:3
 centers(k,:)=G.holes(k).center(:).';
 radii(k)=G.holes(k).radius;
end
plateSideDistances=[tip(1)-xmin,xmax-tip(1), ...
    tip(2)-ymin,ymax-tip(2)];
wallClearance=vecnorm(centers-tip,2,2)-radii;
guideClearance=vecnorm(centers-tip,2,2)-3*radii;
before=norm(tip-prev);
cornell=struct( ...
 'exactNominalStarterTip',norm(tip-[101.6,25.4])<1e-10, ...
 'crackVerticalUpwards', ...
    abs(prev(1)-tip(1))<1e-10&&tip(2)>prev(2), ...
 'allThreeRealHoleWallsOutsideCollar',all(wallClearance>ro), ...
 'allThreeMaterialGuideContoursOutsideCollar', ...
    all(guideClearance>ro), ...
 'allFourOuterPlateSidesOutsideCollar',all(plateSideDistances>ro), ...
 'constructionSegmentBeyondCollar',before>ro, ...
 'frozenP010RingMatchesActualTipFrame',sourceFixed);
fprintf('G2_P010_CORNELL_MIN_HOLE_WALL_MARGIN_MM=%.8f\n', ...
    min(wallClearance)-ro);
fprintf('G2_P010_CORNELL_MIN_GUIDE_MARGIN_MM=%.8f\n', ...
    min(guideClearance)-ro);
fprintf('G2_P010_CORNELL_MIN_PLATE_MARGIN_MM=%.8f\n', ...
    min(plateSideDistances)-ro);
fprintf('G2_P010_CORNELL_CONSTRUCTION_SEGMENT_MM=%.8f\n',before);
if ~all(cell2mat(struct2cell(cornell)))
 R.stage='HOLD_CORNELL_THREE_HOLE_CLEARANCE';
 R.gates=cornell;
 R.failedGates=fieldnames(cornell);
 R.message='Independent Cornell original three-hole/plate/p010 clearance failed.';
 return
end
R.p010CornellPlacementQualified=true;

% Reproduce verified source geometric collar construction: exactly 128 T3
% triangles between 64-sector inner ring and 3.3mm outer rim, with two
% separate crack entry NODES at the negative local tangent. These are not
% physical holes and are not yet joined to any PDE exterior.
outerIdeal=tip+ro*(cos(phi)*t+sin(phi)*n);
outerIdeal=[outerIdeal;outerIdeal(33,:)];
outerIDs=(size(Xu,1)+(1:65))';
Tcol=zeros(128,3);
innerSide=zeros(64,2);outerSide=zeros(64,2);
for j=1:64
 k=mod(j,64)+1;
 i0=ring(j);o0=outerIDs(j);
 if j==33,i0=lowerEntry;o0=outerIDs(65);end
 i1=ring(k);o1=outerIDs(k);
 Tcol(2*j-1,:)=[i0,o0,o1];
 Tcol(2*j,:)=[i0,o1,i1];
 innerSide(j,:)=sort([i0,i1]);
 outerSide(j,:)=sort([o0,o1]);
end
X=[Xu;outerIdeal];T=[Tu;Tcol];
nCore=size(Tu,1);
len12=vecnorm(X(T(:,2),:)-X(T(:,1),:),2,2);
len23=vecnorm(X(T(:,3),:)-X(T(:,2),:),2,2);
len31=vecnorm(X(T(:,1),:)-X(T(:,3),:),2,2);
h=max([len12,len23,len31],[],2);
a=X(T(:,2),:)-X(T(:,1),:);
b=X(T(:,3),:)-X(T(:,1),:);
a2=a(:,1).*b(:,2)-a(:,2).*b(:,1);
clip=@(z)max(-1,min(1,z));
angs=[acosd(clip((len12.^2+len31.^2-len23.^2)./(2*len12.*len31))), ...
      acosd(clip((len12.^2+len23.^2-len31.^2)./(2*len12.*len23))), ...
      acosd(clip((len23.^2+len31.^2-len12.^2)./(2*len23.*len31)))];
minAng=min(angs(:));
raw=sort([T(:,[1 2]);T(:,[2 3]);T(:,[3 1])],2);
[edges,~,ic]=unique(raw,'rows');
inc=accumarray(ic,1);
owner=repmat((1:size(T,1))',3,1);
lo=accumarray(ic,owner,[],@min);
hi=accumarray(ic,owner,[],@max);
adj=inc==2;
maxRatio=max(max(h(lo(adj))./h(hi(adj)), ...
                 h(hi(adj))./h(lo(adj))));
[im,~]=ismember(innerSide,edges,'rows');
[om,~]=ismember(outerSide,edges,'rows');
[~,innerIndices]=ismember(innerSide,edges,'rows');
[~,outerIndices]=ismember(outerSide,edges,'rows');
insideValid=all(im)&&all(inc(innerIndices)==2);
outsideValid=all(om)&&all(inc(outerIndices)==1);
[X6,T6]=T3toT6_fast(X,T);
r6=vecnorm(X6-tip,2,2);
q=ones(size(r6));
q(r6>=2.6)=0;
transition=r6>.4&r6<2.6;
q(transition)=(2.6-r6(transition))/(2.6-.4);
active=find(max(q(T6),[],2)-min(q(T6),[],2)>1e-14);
activeNodes=unique(T6(active,:));
qMaxRadius=max(r6(activeNodes));
inscribedR=rc*cos(pi/64);
qInside=all(active<=nCore) && qMaxRadius<inscribedR;
proposedTipNode=L.sourcePatch.tipNode;
tipCoordOK=isscalar(proposedTipNode)&& ...
 norm(X(proposedTipNode,:)-tip)<1e-9;
regular=struct( ...
 'source15of15',local15, ...
 'source2788T3And64Sectors',sourceFixed, ...
 'CornellThreeHolePlateClearances', ...
    all(cell2mat(struct2cell(cornell))), ...
 'analyticCollar128T3And65OuterEntryNodes', ...
    size(Tcol,1)==128&&numel(outerIDs)==65, ...
 'allRegularT3AreasPositive',all(a2>0), ...
 'regularT3MinAngleAtLeast20',minAng>=20, ...
 'regularT3NeighborRatioAtMost1p8',maxRatio<=1.8, ...
 'exact64TwoOwnerInnerSeamEdges',insideValid, ...
 'exact64OneOwnerOuterRimEdges',outsideValid, ...
 'T6HasEveryUniqueMidsideOnce', ...
    size(X6,1)==size(X,1)+size(edges,1), ...
 'singlePhysicalTipCorrect',tipCoordOK, ...
 'FEqSupportParentsInsideP010',qInside&&numel(active)==2443, ...
 'physicalSourceAndNoLEFM', ...
    ~J.simulation_permit&&logical(L.summary.geometryOnly));
gateVals=cell2mat(struct2cell(regular));
R.gates=regular;
gateNames=fieldnames(regular);
R.failedGates=gateNames(~gateVals);
R.summary=struct( ...
 'upstreamSourceRef','a14d8872ab588ac551e41b4531bffee2dcd0ce2c', ...
 'upstreamSourceLocalGates',R.summary.upstreamSourceLocalGates, ...
 'upstreamSourceLocalGatesTotal',R.summary.upstreamSourceLocalGatesTotal, ...
 'tip_mm',tip,'mouth_mm',mouth,'deltaOnlyConstruction_mm',delta, ...
 'tangent',t,'p010CoreRadius_mm',rc, ...
 'collarThickness_mm',dr,'outerRimRadius_mm',ro, ...
 'ringT3Elements',nCore,'collarT3Elements',size(Tcol,1), ...
 'regularBlockT3Elements',size(T,1), ...
 'regularBlockT3Nodes',size(X,1), ...
 'regularBlockT6Nodes',size(X6,1), ...
 'coreOuterAngularSectors',64, ...
 'minAngle_deg',minAng,'maxNeighborLongestEdgeRatio',maxRatio, ...
 'innerSeamTwoOwnerCount',nnz(inc(innerIndices)==2), ...
 'outerRimOneOwnerCount',nnz(inc(outerIndices)==1), ...
 'qActiveT6Parents',numel(active), ...
 'qSupportMaxRadius_mm',qMaxRadius, ...
 'qSupportCoreInradius_mm',inscribedR, ...
 'threeHoleWallClearance_mm',wallClearance(:).', ...
 'threeGuideClearance_mm',guideClearance(:).', ...
 'plateSideClearance_mm',plateSideDistances, ...
 'collarMarginToHoleWall_mm',min(wallClearance)-ro, ...
 'collarMarginToGuideContour_mm',min(guideClearance)-ro, ...
 'collarMarginToPlateSide_mm',min(plateSideDistances)-ro, ...
 'sourceJSON',char(o.JsonPath));
fprintf('G2_P010_REGULAR_GATES=%d/%d\n',nnz(gateVals),numel(gateVals));
fprintf('G2_P010_REGULAR_MIN_ANGLE_DEG=%.8f\n',minAng);
fprintf('G2_P010_REGULAR_MAX_NEIGHBOR_RATIO=%.8f\n',maxRatio);
fprintf('G2_P010_REGULAR_CORE_T3=%d\n',nCore);
fprintf('G2_P010_REGULAR_COLLAR_T3=%d\n',size(Tcol,1));
fprintf('G2_P010_REGULAR_Q_ACTIVE_T6=%d\n',numel(active));
fprintf('G2_P010_REGULAR_INNER_SEAM=%d\n',R.summary.innerSeamTwoOwnerCount);
fprintf('G2_P010_REGULAR_OUTER_RIM=%d\n',R.summary.outerRimOneOwnerCount);
R.pass=all(gateVals);
if R.pass
 R.stage='P010_ISOLATED_CORNELL_REGULAR_BLOCK_PASS';
 R.message='Frozen p010 + collar accepted in isolation; global exterior join NOT built.';
else
 R.stage='HOLD_P010_ISOLATED_REGULAR_BLOCK';
 R.message=strjoin(R.failedGates,', ');
end
R.coord3=X;R.connect3=T;
R.coord6=X6;R.connect6=T6;
R.tipNode=proposedTipNode;R.nodalQ=q;
R.qActiveT6Rows=active;
R.sourceP010=L;
R.p010GlobalProtectedMeshQualified=false;
R.approvedForLEFM=false;
fprintf('G2_P010_ISOLATED_PASS=%d\n',R.pass);
fprintf('G2_P010_GLOBAL_JOINED=0; NO_LEFM=1; NO_CRACK_GROWTH=1\n');
if o.Plot
 fig=figure('Color','w','Visible','off', ...
     'Name','Cornell #1 isolated regular p010 mesh + 0.3 mm collar');
 triplot(T,X(:,1)-tip(1),X(:,2)-tip(2), ...
      'Color',[.42,.58,.70]);hold on;
 th=linspace(0,2*pi,350)';
 plot(rc*cos(th),rc*sin(th),'r-','LineWidth',1.1);
 plot(ro*cos(th),ro*sin(th),'Color',[.15,.62,.29], ...
    'LineWidth',1.6);
 plot(2.6*cos(th),2.6*sin(th),'m:','LineWidth',1.2);
 plot(0,0,'k.','MarkerSize',14);
 axis equal;grid on;box on;
 xlim([-3.65,3.65]);ylim([-3.65,3.65]);
 xlabel('x - x_{tip} (mm)');ylabel('y - y_{tip} (mm)');
 title(sprintf('Frozen p010 (2,788 T3) + 0.3 mm collar (128 T3) — %s', ...
    R.stage),'Interpreter','none');
 R.figure=fig;
end
end
