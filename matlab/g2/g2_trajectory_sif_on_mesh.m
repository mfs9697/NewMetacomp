function K=g2_trajectory_sif_on_mesh(D,mat,policy)
%G2_TRAJECTORY_SIF_ON_MESH New numerical tip: solve -> BLIND COD -> EDI -> compare.
% Derived from the verified WP3.2 solver, with the PRE flow's actual blind
% COD-before-EDI order, whole-crack opening and sign diagnostics added.
% No previous-step U, K, traction, q or face IDs are imported. No toughness
% or onset criterion. Units: mm, N, MPa; convert K to MPa sqrt(m)/kN.
required={'X6','T6','crackPolyline','tipTangent','upperBankT6', ...
 'lowerBankT6','extraVertexNodes','extraVertexXY'};
assert(all(isfield(D,required)),'G2Trajectory:SIFMeshSchema', ...
 'New protected mesh lacks required signed-COD and physical BVP data.');
P=D.crackPolyline;tip=P(end,:);t=D.tipTangent(:).';
assert(abs(norm(t)-1)<1e-10,'G2Trajectory:Tangent', ...
 'Terminal crack-tip tangent is not a unit vector.');
thick=policy.bvp.thickness_mm;
f=policy.bvp.P_N/thick;
N=size(D.X6,1);
% WP3.4 HOLD-1 fix: jsondecode returns policy arrays as 2x1 columns; compare as rows.
nodeAt=@(xy)D.extraVertexNodes(vecnorm(D.extraVertexXY-reshape(xy,1,2),2,2)<1e-9);
pin=nodeAt(policy.bvp.pin_mm);
roller=nodeAt(policy.bvp.roller_mm);
loadNode=nodeAt(policy.bvp.load_mm);
assert(isscalar(pin)&&isscalar(roller)&&isscalar(loadNode), ...
 'G2Trajectory:BVPAnchors','Missing pin, roller or load vertex.');
F=zeros(2*N,1);F(2*loadNode)=-f;
bc=struct('fixedDofs',[2*pin-1;2*pin;2*roller], ...
 'fixedValues',[0;0;0],'F',F);
S=g2_t6_elasticity(D.X6,D.T6,mat,bc);
reac=S.reactions;
span=policy.bvp.roller_mm(1)-policy.bvp.pin_mm(1);
momentArm=policy.bvp.load_mm(1)-policy.bvp.pin_mm(1);
sta=[abs(reac(1))/f,abs(reac(2)+reac(3)-f)/f, ...
 abs(policy.bvp.pin_mm(1)*reac(2)+ ...
 policy.bvp.roller_mm(1)*reac(3)-policy.bvp.load_mm(1)*f)/(abs(f)*span), ...
 abs(reac(3)/f-momentArm/span), ...
 abs(reac(2)/f-(span-momentArm)/span)];
% Blind displacement method first: no EDI or q passed to the extractor.
lastLen=norm(P(end,:)-P(end-1,:));
C=g2_sif_cod_banks(D.X6,S.u,mat,tip,t,D.upperBankT6, ...
 D.lowerBankT6,lastLen,[.1 1.5]);
% Independent full-polyline crack opening, from registered bank twins.
U=D.upperBankT6(:);L=D.lowerBankT6(:);
assert(numel(U)==numel(L)&&numel(U)>3&& ...
 max(vecnorm(D.X6(U,:)-D.X6(L,:),2,2))<1e-9, ...
 'G2Trajectory:WholeCrackTwins','Saved bank node pairs invalid.');
d=[S.u(2*U-1)-S.u(2*L-1),S.u(2*U)-S.u(2*L)];
ds=diff(P,1,1);lens=vecnorm(ds,2,2);tt=ds./lens;nn=[-tt(:,2),tt(:,1)];
staPath=[0;cumsum(lens)];
arc=nan(numel(U),1);segID=ones(numel(U),1);
for k=1:numel(U)
 x=D.X6(U(k),:);best=inf;
 for j=1:size(tt,1)
  h=max(0,min(lens(j),dot(x-P(j,:),tt(j,:))));
  distance=norm(x-(P(j,:)+h*tt(j,:)));
  if distance<best,best=distance;segID(k)=j;arc(k)=staPath(j)+h;end
 end
 assert(best<1e-8,'G2Trajectory:BankOffPolyline', ...
     'Whole-crack bank node %d is off the accepted polyline.',k);
end
opening=sum(d.*nn(segID,:),2);
% Ignore the one shared physical tip (exactly zero opening), but not kinks.
minOpening=min(opening);
% Now EDI, using exactly the previously registered FE-nodal q annuli.
an=[.4 2.6;.2 1.0;.4 1.6;.8 2.6;1.2 2.4];
ed=zeros(size(an,1),3);qmax=0;
for j=1:size(an,1)
 E=g2_sif_interaction(D.X6,D.T6,S.u,mat,tip,t,an(j,1),an(j,2),6);
 ed(j,:)=[E.KI,E.KII,E.J];qmax=max(qmax,E.maxSupportRadius);
end
E4=g2_sif_interaction(D.X6,D.T6,S.u,mat,tip,t,.4,2.6,4);
[~,Ep]=g2_plane_D(mat);
Kr=hypot(ed(1,1),ed(1,2));
assert(isfinite(Kr)&&Kr>0,'G2Trajectory:ZeroSIF','No tensile signed SIF exists.');
ratio=abs(ed(1,2)/ed(1,1));
signMatch=sign(ed(1,2))==sign(C.KII);
v=policy.verification;
qGate=qmax<policy.numerics.coreRadius_mm*cos(pi/policy.numerics.protectedSectors);
criteria=struct( ...
 'elasticEquilibrium',S.relativeResidual<=v.elasticRelativeResidualMax&&max(sta)<=v.elasticRelativeResidualMax, ...
 'blindCODversusEDI',max(abs([ed(1,1)-C.KI,ed(1,2)-C.KII]))/Kr<=v.COD_EDI_maxFractionOfKref, ...
 'contourIndependence',max(max(ed(:,1:2))-min(ed(:,1:2)))/Kr<=v.pathSpread_maxFraction, ...
 'JenergyIdentity',abs(ed(1,3)/((ed(1,1)^2+ed(1,2)^2)/Ep)-1)<=v.JEnergyIdentityMaxFraction, ...
 'EDIquadrature',max(abs([E4.KI-ed(1,1),E4.KII-ed(1,2)]))/Kr<=v.quadratureDriftMaxFraction, ...
 'qSupportInsideCore',qGate, ...
 'wholeCrackOpening',minOpening>=v.minWholeCrackNormalOpening_mm, ...
 'KIpositive',ed(1,1)>0, ...
 'conditionalHighMixityKIIagreement',ratio<=v.highMixitySignGateAbsKIIoverKI||signMatch);
values=cell2mat(struct2cell(criteria));fields=fieldnames(criteria);
K=struct('pass',all(values),'status','HOLD_SIF_VERIFICATION', ...
 'criteria',criteria,'failedCriteria',{fields(~values)}, ...
 'KI',ed(1,1),'KII',ed(1,2),'J',ed(1,3), ...
 'KI_COD',C.KI,'KII_COD',C.KII, ...
 'KI_MPa_sqrt_m_per_kN',ed(1,1)*sqrt(1000), ...
 'KII_MPa_sqrt_m_per_kN',ed(1,2)*sqrt(1000), ...
 'fullPolyOpeningMin_mm',minOpening,'fullPolyOpening_mm',opening, ...
 'wholeCrackArclength_mm',arc,'holeOrContactResolved',false, ...
 'conditionalModeIISignGateEnforced',ratio>v.highMixitySignGateAbsKIIoverKI, ...
 'KII_sign_edi_vs_cod_match',signMatch,'qSupportMaxRadius_mm',qmax, ...
 'relativeResidual',S.relativeResidual,'staticsMax',max(sta), ...
 'EDI_all',ed,'codFitPairs',C.pairsInWindow, ...
 'EDI4x4',[E4.KI,E4.KII],'statics',sta, ... % WP3.4: report values behind the flags
 'physicalFractureGrowthProven',false);
if K.pass,K.status='TRAJECTORY_NUMERICAL_SIF_VERIFIED';end
fprintf('G2_TRAJECTORY_SIF_PASS=%d, KI=%.9g KII=%+.9g MPa sqrt(m)/kN\n', ...
 K.pass,K.KI_MPa_sqrt_m_per_kN,K.KII_MPa_sqrt_m_per_kN);
fprintf('G2_TRAJECTORY_COD_EDI_REL=%.7g WHOLE_CRACK_OPENING_MIN_MM=%.7g\n', ...
 max(abs([ed(1,1)-C.KI,ed(1,2)-C.KII]))/Kr,minOpening);
end
