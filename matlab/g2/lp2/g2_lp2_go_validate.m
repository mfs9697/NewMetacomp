function G=g2_lp2_go_validate(G,C,loadContract)
%G2_LP2_GO_VALIDATE  Pure validation of a decoded GO_LP2A record. Opens no file, writes nothing.
% One named campaign: the four cases H, stiff13, soft2, soft1, states S5-S8, at most 16 solves.
% C fields used: policySHA256, g2SourceSHA256, lp2SourceSHA256, parentManifestSHA256, token,
% policy.authorization. loadContract: @(relpath) -> struct(exists, sha256, text).
UN='G2LP2:HOLD_UNAUTHORIZED_STATE';SRC='G2LP2:HOLD_SOURCE';
f={'decision','reviewStatus','scientificReviewer','reviewURL','approvedPolicySHA256','approvedG2SourceSHA256', ...
 'approvedLP2SourceSHA256','approvedParentManifestSHA256','approvedToken','approvedCases','maxStateIndex','maxSolves', ...
 'revocationRequired','contractEvidenceFile','contractEvidenceSHA256','approvedRunName','campaignId','campaignScope'};
assert(isstruct(G)&&isscalar(G)&&all(isfield(G,f)),UN,'Incomplete GO_LP2A record.');
assert(ischar(G.decision)&&strcmp(G.decision,'GO_LP2A_PHYSICAL')&&ischar(G.reviewStatus)&&strcmp(G.reviewStatus,'REVIEWED_ACCEPTED')&& ...
 ischar(G.scientificReviewer)&&~isempty(strtrim(G.scientificReviewer))&&ischar(G.reviewURL)&& ...
 startsWith(G.reviewURL,'https://github.com/mfs9697/NewMetacomp/'),UN,'GO_LP2A decision or review proof is absent or invalid.');
au=C.policy.authorization;
assert(ischar(G.campaignScope)&&strcmp(G.campaignScope,'LP2A_S5_S8_MAX16')&&ischar(G.approvedRunName)&& ...
 ~isempty(regexp(G.approvedRunName,'^run_[a-zA-Z0-9_]+$','once'))&&~any(strcmp(G.approvedRunName,cellstr(au.forbiddenRunNames)))&& ...
 ischar(G.campaignId)&&~isempty(regexp(G.campaignId,'^[A-Za-z0-9_-]{3,64}$','once'))&&~any(strcmp(G.campaignId,cellstr(au.forbiddenCampaignIds))), ...
 UN,'LP2-A campaign scope, run name or campaign ID is invalid.');
assert((iscellstr(G.approvedCases)||isstring(G.approvedCases))&&isequal(reshape(cellstr(G.approvedCases),1,[]),{'H','stiff13','soft2','soft1'})&& ...
 isnumeric(G.maxStateIndex)&&isscalar(G.maxStateIndex)&&G.maxStateIndex==8&&isnumeric(G.maxSolves)&&isscalar(G.maxSolves)&& ...
 G.maxSolves==16&&isequal(G.revocationRequired,true),UN,'GO_LP2A must list the four cases, S8, sixteen solves and revocation.');
assert(strcmpi(G.approvedPolicySHA256,C.policySHA256)&&strcmpi(G.approvedG2SourceSHA256,C.g2SourceSHA256)&& ...
 strcmpi(G.approvedLP2SourceSHA256,C.lp2SourceSHA256)&&strcmpi(G.approvedParentManifestSHA256,C.parentManifestSHA256)&& ...
 ischar(G.approvedToken)&&strcmp(G.approvedToken,C.token),SRC,'GO_LP2A does not bind the exact policy, sources, parents and token.');
p=G.contractEvidenceFile;
assert(ischar(p)&&startsWith(p,au.contractEvidenceDir)&&isempty(strfind(p,'..'))&&~isempty(regexp(p,'^[A-Za-z0-9_./-]+$','once')), ...
 SRC,'LP2-A contract evidence path is not pinned.');
E=loadContract(p);
assert(isstruct(E)&&isscalar(E)&&isfield(E,'exists')&&isequal(E.exists,true)&&ischar(E.sha256)&&ischar(G.contractEvidenceSHA256)&& ...
 strcmpi(E.sha256,G.contractEvidenceSHA256),SRC,'LP2-A contract evidence bytes are absent or changed.');
T=jsondecode(E.text);
assert(isstruct(T)&&all(isfield(T,{'pass','passed','total','physicalSolves','negativeTestsPassed','token'})),UN,'LP2-A contract evidence lacks required fields.');
assert(isequal(T.pass,true)&&T.passed==T.total&&T.total>=30&&T.physicalSolves==0&&isequal(T.negativeTestsPassed,true),UN,'LP2-A contract qualification has not passed.');
assert(ischar(T.token)&&strcmp(T.token,C.token),SRC,'LP2-A contract evidence was produced for another token.');
end
