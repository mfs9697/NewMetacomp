function G=main_m1i_increment_ring_geometry_only(varargin)
%MAIN_M1I_INCREMENT_RING_GEOMETRY_ONLY
% GEOMETRY-ONLY increment-aware local crack-tip ring for EdgeCrackHoleLEFM.
%
% Adapts the EXISTING verified compact p010 2--7.2mm paired analytical
% disk/annulus by uniform similarity scaling, translation and rotation.
% The original builders, original 50mm physical FEM solutions, q source,
% COD fits and all other computational source are UNMODIFIED.
%
% DEFAULT CONTROL: original straight crack 0..50mm; trial increment 4mm;
% new straight segment oriented by Turn_deg relative to the prior
% segment, core radius = .75*increment = 3mm, EDI .1..65*increment.
% This is a candidate geometry, not a crack-angle prediction.
%
% The 4mm candidate scales the *entire* qualified p010 analytic patch
% by 3/7.2, not merely the 11-ring disk:
% 2mm historical disk -> .833333mm, first tip edge .1 -> .041667mm;
% 2,788 unchanged T3 patch triangles, 64 outer-sector coordinates.
% No claim about new GLOBAL T6 nodes or free DOFs can be made before a
% separate full native MATLAB PDE exterior build + conforming join.
%
%  addpath(genpath(pwd))
%  G=main_m1i_increment_ring_geometry_only('Delta_mm',4, ...
%       'Turn_deg',10,'Plot',true);
%  disp(G.summary);disp(G.gates);disp(G.pass)
%
% NO generateMesh / stiffness / elasticity / EDI / COD / SIF / growth.
ip=inputParser;
addParameter(ip,'Delta_mm',4,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
addParameter(ip,'Turn_deg',0,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&abs(x)<=90);
addParameter(ip,'PriorCrackPolyline_m',[0,0;.05,0], ...
    @(x)isnumeric(x)&&size(x,2)==2&&size(x,1)>=2&&all(isfinite(x(:))));
addParameter(ip,'CoreOverDelta',.75,@(x)isnumeric(x)&&isscalar(x)&&x>0&&x<1);
addParameter(ip,'EDIInnerOverDelta',.10,@(x)isnumeric(x)&&isscalar(x)&&x>0);
addParameter(ip,'EDIOuterOverDelta',.65,@(x)isnumeric(x)&&isscalar(x)&&x>0);
addParameter(ip,'MinCoreBufferOverDelta',.05, ...
    @(x)isnumeric(x)&&isscalar(x)&&x>=0);
addParameter(ip,'Plot',true,@(x)islogical(x)&&isscalar(x));
parse(ip,varargin{:});o=ip.Results;
assert(o.EDIInnerOverDelta<o.EDIOuterOverDelta && ...
       o.EDIOuterOverDelta<o.CoreOverDelta && ...
       o.MinCoreBufferOverDelta<o.CoreOverDelta-o.EDIOuterOverDelta, ...
    'M1IRing:CandidateRadii','Require positive EDI annulus inside core.');
poly=o.PriorCrackPolyline_m;
seg=diff(poly,1,1);
assert(all(vecnorm(seg,2,2)>1e-12), ...
    'M1IRing:ZeroLengthPreviousCrack','Every previous segment must be positive.');
priorTip=poly(end,:);
direction=atan2(seg(end,2),seg(end,1))+deg2rad(o.Turn_deg);
t=[cos(direction),sin(direction)];
n=[-sin(direction),cos(direction)];
rotation=[t(:),n(:)];
da=o.Delta_mm/1000;
tip=priorTip+da*t;
rCore=o.CoreOverDelta*da;
rEDIin=o.EDIInnerOverDelta*da;
rEDIout=o.EDIOuterOverDelta*da;
rInnerDisk=(2/7.2)*rCore;
scale=rCore/.0072;

% Byte-unchanged original p010 disk+annulus builder. It constructs the
% verified 7.2mm geometry before the rigid similarity transformation.
base=build_m1i_trial_tip_annulus_p010( ...
    'InnerRadius',.002,'OuterRadius',.0072, ...
    'Htip',.0001,'Ntheta',64,'RadialIntervals',16);
assert(size(base.connect3,1)==2788 && ...
       base.nInnerDiskTriangles==724 && ...
       base.nAnnulusTriangles==2064 && ...
       base.annulusInfo.Ntheta==64 && ...
       base.annulusInfo.Nr==16 && ...
       numel(base.innerDisk.radialRings_m)==11 && ...
       numel(base.originalAnnulus.rings{end})==64, ...
    'M1IRing:SourcePatchChanged', ...
    'Qualified 11-ring / 16-band / 64-sector source patch changed.');
Xlocal=scale*base.coord3;
X=Xlocal*rotation.'+tip;
T=base.connect3;
[X6,T6]=T3toT6_fast(X,T);
N=size(T,1);
assert(size(T6,1)==2788 && size(T6,2)==6, ...
    'M1IRing:BadT6','T3-to-T6 conversion failed.');

% Independent genuine T3 geometry quality; area and positive affine T6
% Jacobian are preserved under a positive-determinant rigid similarity.
a=X(T(:,2),:)-X(T(:,1),:);
b=X(T(:,3),:)-X(T(:,1),:);
area=.5*(a(:,1).*b(:,2)-a(:,2).*b(:,1));
len12=vecnorm(a,2,2);
len23=vecnorm(X(T(:,3),:)-X(T(:,2),:),2,2);
len31=vecnorm(b,2,2);
h=max([len12,len23,len31],[],2);
quality=4*sqrt(3)*area./(len12.^2+len23.^2+len31.^2);
clip=@(v)min(1,max(-1,v));
ang1=acosd(clip((len12.^2+len31.^2-len23.^2)./(2*len12.*len31)));
ang2=acosd(clip((len12.^2+len23.^2-len31.^2)./(2*len12.*len23)));
ang3=acosd(clip((len23.^2+len31.^2-len12.^2)./(2*len23.*len31)));
minAngle=min([ang1;ang2;ang3]);

% Unique topological edges, real two-owner inner disk join and one-owner
% outer ring. At the negative-x entry the upper/lower bank IDs MUST differ.
edgePairs=sort([T(:,[1 2]);T(:,[2 3]);T(:,[3 1])],2);
[edges,~,ic]=unique(edgePairs,'rows');
count=accumarray(ic,1);
owner=repmat((1:N)',3,1);
ownerLo=accumarray(ic,owner,[],@min);
ownerHi=accumarray(ic,owner,[],@max);
adj=count==2;
ratio=max(max(h(ownerLo(adj))./h(ownerHi(adj)), ...
              h(ownerHi(adj))./h(ownerLo(adj))));
r3=vecnorm(X-tip,2,2);
tol=max(2e-12,2e-10*rCore);
outer=all(abs(r3(edges)-rCore)<tol,2);
inner=all(abs(r3(edges)-rInnerDisk)<tol,2);
boundary=count==1;
outerEdges=edges(outer,:);
outerRingIDs=unique(outerEdges(:));
outerCount=nnz(outer);
innerCount=nnz(inner);

% Geometrically coincident, topologically separate physical crack banks.
upper=base.upperFaceNodes(:);lower=base.lowerFaceNodes(:);
tipID=base.tipNode;
bankT3=numel(upper)==numel(lower) && ...
       isequal(intersect(upper,lower),tipID) && ...
       max(vecnorm(X(upper,:)-X(lower,:),2,2))<1e-11 && ...
       numel(upper)>2;
edgeMids=T6(:,4:6);
midVector=[edgeMids(:,1);edgeMids(:,2);edgeMids(:,3)];
midLo=accumarray(ic,midVector,[],@min);
midHi=accumarray(ic,midVector,[],@max);
uPairs=sort([upper(1:end-1),upper(2:end)],2);
lPairs=sort([lower(1:end-1),lower(2:end)],2);
[fu,iu]=ismember(uPairs,edges,'rows');
[fl,il]=ismember(lPairs,edges,'rows');
assert(all(fu)&&all(fl) && all(midLo==midHi), ...
    'M1IRing:FaceOrMidsideTopology', ...
    'Failed T6 crack-face edges or global midside node consistency.');
up6=unique([upper;midLo(iu)]);lo6=unique([lower;midLo(il)]);
localX=(X6-tip)*t.';
[~,aix]=sort(localX(up6));up6=up6(aix);
[~,bix]=sort(localX(lo6));lo6=lo6(bix);
bankT6=isequal(intersect(up6,lo6),tipID) && ...
       numel(up6)==2*numel(upper)-1 && ...
       numel(lo6)==2*numel(lower)-1 && ...
       max(vecnorm(X6(up6,:)-X6(lo6,:),2,2))<1e-11;
closestLip=min(vecnorm(X6(up6(up6~=tipID),:)-tip,2,2));
tipFan=T(any(T==tipID,2),:);
tipNeighbors=unique(tipFan(:));tipNeighbors(tipNeighbors==tipID)=[];
actualFirstTipEdge=min(vecnorm(X(tipNeighbors,:)-tip,2,2));
tipFanAndFaceMidValid=size(tipFan,1)==6 && ...
    numel(tipNeighbors)==7 && ...
    abs(actualFirstTipEdge-.0001*scale)<1e-11 && ...
    abs(closestLip-actualFirstTipEdge/2)<1e-11;

% Original source's FE-NODAL radial weight, now with new proposed physical
% annulus. Significant support is evaluated with ALL SIX T6 nodes per
% element, including the interpolation halo, not only nominal radii.
r6=vecnorm(X6-tip,2,2);
q=ones(size(r6));
q(r6>=rEDIout)=0;
between=(r6>rEDIin & r6<rEDIout);
q(between)=(rEDIout-r6(between))/(rEDIout-rEDIin);
sp=max(q(T6),[],2)-min(q(T6),[],2);
qActive=sp>1e-14;
assert(any(qActive),'M1IRing:NoQSupport', ...
    'Proposed FE-nodal-q annulus has no active T6 elements.');
qNodeIDs=unique(T6(qActive,:));
maxQR=max(r6(qNodeIDs));
coreInradius=rCore*cos(pi/64);
buffer=coreInradius-maxQR;
allExteriorRingQZero=all(q(outerRingIDs)==0);
minBuffer=o.MinCoreBufferOverDelta*da;

% Geometry-only clearance against EXISTING crack polyline, true circles,
% and physical exterior rectangle. New straight segment occupies exactly
% the inner portion of the negative local x-axis.
oldCrackClearance=inf;
for j=1:size(poly,1)-1
    v=poly(j+1,:)-poly(j,:);
    lam=min(1,max(0,dot(tip-poly(j,:),v)/dot(v,v)));
    nearest=poly(j,:)+lam*v;
    oldCrackClearance=min(oldCrackClearance,norm(tip-nearest));
end
holeCenters=[.100,-.050;.170,+.050];
holeRadii=[.025;.030];
holeMargin=vecnorm(holeCenters-tip,2,2)-holeRadii-rCore;
plateMargin=min([tip(1),.300-tip(1),.200-abs(tip(2))])-rCore;
previousKinkOutside=oldCrackClearance-rCore>1e-10;
clearGeometry=all(holeMargin>0) && plateMargin>0 && ...
              previousKinkOutside;
sourceDiskQuality=base.innerDisk.qualityMin>.85 && ...
                  base.innerDisk.minAngle_deg>=30;

gates=struct( ...
 'originalP010StructuredSourceUnchanged', ...
     size(T,1)==2788 && ...
     isequal(T,base.connect3) && ...
     size(base.innerDisk.connect3,1)==724, ...
 'incrementPositiveAndCoreSmallerThanIncrement',da>rCore, ...
 'similarityTipAndRingRadiiCorrect', ...
     abs(max(r3)-rCore)<1e-11 && ...
     abs(norm(tip-priorTip)-da)<1e-12 && ...
     abs(rInnerDisk-(2/7.2)*rCore)<1e-12, ...
 'originalDiskSpecificQualityPreserved',sourceDiskQuality, ...
 'wholeRingAreaAndT6JacobiansPositive',all(area>0) && ...
     all(isfinite(area)) && size(X6,1)>size(X,1), ...
 'wholeRingMinimumAngleAndShapeQualityRetained', ...
     minAngle>=20 && min(quality)>=.75-1e-10, ...
 'wholeRingMaximumNeighborRatioAtMost1p8',ratio<=1.8+1e-12, ...
 'outer64BoundaryEdgesAndInner64TwoOwnerEdges', ...
     outerCount==64 && all(boundary(outer)) && ...
     innerCount==64 && all(count(inner)==2), ...
 'uniqueT6MidsidesAndRealPairedCrackBanks', ...
     all(midLo==midHi) && bankT3 && bankT6, ...
 'actualSixTriangleTipFanAndFirstT6Midpoint',tipFanAndFaceMidValid, ...
 'oldCrackAndPreviousKinkOutsideProtectedCore',previousKinkOutside, ...
 'bothTrueHoleDisksOutsideCore',all(holeMargin>0), ...
 'entireRingInsidePhysicalPlate',plateMargin>0, ...
 'allFEqSupportStrictlyInsidePairedCore', ...
     allExteriorRingQZero && buffer>minBuffer, ...
 'allProposedEDIRadiiOrderedInsideCore', ...
     rEDIin>0 && rEDIin<rEDIout && rEDIout<rCore);
v=cell2mat(struct2cell(gates));
G=struct('pass',all(v), ...
    'gates',gates, ...
    'sourcePatch',base, ...
    'coord3',X,'connect3',T,'coord6',X6,'connect6',T6, ...
    'upperBankT6',up6,'lowerBankT6',lo6, ...
    'qNodal',q,'qActiveT6Rows',find(qActive), ...
    'tip_m',tip,'priorTip_m',priorTip,'newDirection_rad',direction, ...
    'outerRingGeometricEdges',outerEdges, ...
    'summary',struct( ...
       'previousTip_mm',1000*priorTip, ...
       'newTip_mm',1000*tip, ...
       'trialTurn_deg',o.Turn_deg, ...
       'trialGlobalNewSegmentAngle_deg',rad2deg(direction), ...
       'Delta_mm',o.Delta_mm, ...
       'coreOverDelta',o.CoreOverDelta, ...
       'coreRadius_mm',1000*rCore, ...
       'diskRadius_mm',1000*rInnerDisk, ...
       'scaledFirstTipT3Edge_mm',1000*actualFirstTipEdge, ...
       'closestT6BankSample_mm',1000*closestLip, ...
       'ringScaleFromQualifiedP010',scale, ...
       'diskRadialRings',11, ...
       'annulusRadialIntervals',16, ...
       'outerRingAngularSectors',64, ...
       'patchT3Cells',size(T,1), ...
       'patchT6Nodes',size(X6,1), ...
       'patchT6FacePairsWithoutTip',numel(up6)-1, ...
       'outerRingChordTarget_mm',1000*2*rCore*sin(pi/64), ...
       'minimumT3Angle_deg',minAngle, ...
       'minimumT3Quality',min(quality), ...
       'maximumNeighborEdgeRatio',ratio, ...
       'ediInner_mm',1000*rEDIin, ...
       'ediOuter_mm',1000*rEDIout, ...
       'activeFEqT6PatchCells',nnz(qActive), ...
       'maxFEqSupportNodeRadius_mm',1000*maxQR, ...
       'coreInscribedRadius_mm',1000*coreInradius, ...
       'effectiveFEqCoreBuffer_mm',1000*buffer, ...
       'requiredMinimumBuffer_mm',1000*minBuffer, ...
       'previousCrackClearance_mm',1000*oldCrackClearance, ...
       'holeMargins_mm',1000*holeMargin(:).', ...
       'plateMargin_mm',1000*plateMargin, ...
       'nativeMATLABExteriorBuilt',false, ...
       'fullConformingGlobalT6MeshBuilt',false, ...
       'globalFreeDOFsDetermined',false, ...
       'originalFEMModifiedOrSolved',false, ...
       'EDIOrCODComputed',false, ...
       'crackPropagated',false, ...
       'geometryOnly',true), ...
    'candidateOnly',true, ...
    'hasQualifiedGlobalMATLABExterior',false, ...
    'hasQualifiedPhysicalElasticity',false);
fprintf('INCREMENT-AWARE RING: %d/%d local geometry gates\n', ...
    nnz(v),numel(v));
disp(G.summary);disp(G.gates);disp(G.pass);
if ~o.Plot,return;end
f=figure('Color','w','Name','Increment-aware crack-tip ring (geometry ONLY)');
triplot(T,1000*X(:,1),1000*X(:,2),'Color',[.63,.77,.84]);
hold on;
plot(1000*poly(:,1),1000*poly(:,2),'k-','LineWidth',2);
plot(1000*[priorTip(1),tip(1)], ...
     1000*[priorTip(2),tip(2)],'Color',[.88,.41,.20], ...
     'LineWidth',2.2);
plot(1000*tip(1),1000*tip(2),'o', ...
     'MarkerFaceColor',[.05,.52,.42], ...
     'MarkerEdgeColor',[.05,.52,.42]);
phi=linspace(0,2*pi,300);
plot(1000*(tip(1)+rEDIin*cos(phi)), ...
     1000*(tip(2)+rEDIin*sin(phi)),'g:');
plot(1000*(tip(1)+rEDIout*cos(phi)), ...
     1000*(tip(2)+rEDIout*sin(phi)),'r--');
axis equal;grid on;box on;
% Zoom to the new physical tip and upstream kink, not the full 50mm
% historical crack.  Plotting NEVER changes the physical geometry.
viewRadius_mm=1000*(rCore+0.5*da);
xlim(1000*tip(1)+viewRadius_mm*[-1,1]);
ylim(1000*tip(2)+viewRadius_mm*[-1,1]);
xlabel('x (mm)');ylabel('y (mm)');
title(sprintf('Increment %.3g mm; trial turn %+g deg; geometry only', ...
     o.Delta_mm,o.Turn_deg));
G.figure=f;
end
