function G=g2_m5x6_go_validate(G,C,loadContract)
%G2_M5X6_GO_VALIDATE  Pure validation of a decoded GO_M5_X6 record. Opens no file, writes nothing.
% Same structure as g2_a1_go_validate, for the separate M5-X6 scope: one named campaign of at
% most six crossed fixed-geometry S4 B9 solves with the six fixed configuration identities.
%   C             context fields used: planSHA256, a1SourceSHA256, x6SourceSHA256,
%                 meshManifestSHA256, token, plan.authorization (forbidden names, contract dir)
%   loadContract  @(relpath) -> struct(exists, sha256, text)   (injected; no file access here)
% HOLD_UNAUTHORIZED_STATE: absent/invalid decision, review proof, scope, run name, campaign ID,
% configuration list, attempt ceiling, revocation commitment or contract qualification.
% HOLD_SOURCE: any plan / source / mesh-manifest / token / contract-bytes binding.
% The revoked A0 and A1 GOs, run names and campaign IDs can never satisfy this validator.
UN='G2M5X6:HOLD_UNAUTHORIZED_STATE';SRC='G2M5X6:HOLD_SOURCE';
fields={'decision','reviewStatus','scientificReviewer','reviewURL','approvedPlanSHA256', ...
 'approvedA1SourceSHA256','approvedX6SourceSHA256','approvedMeshManifestSHA256','approvedToken', ...
 'approvedConfigurations','maxSolves','revocationRequired','contractEvidenceFile', ...
 'contractEvidenceSHA256','approvedRunName','campaignId','campaignScope'};
assert(isstruct(G)&&isscalar(G)&&all(isfield(G,fields)),UN,'Incomplete GO_M5_X6 record.');
assert(ischar(G.decision)&&strcmp(G.decision,'GO_M5_X6_PHYSICAL')&& ...
 ischar(G.reviewStatus)&&strcmp(G.reviewStatus,'REVIEWED_ACCEPTED')&& ...
 ischar(G.scientificReviewer)&&~isempty(strtrim(G.scientificReviewer))&& ...
 ischar(G.reviewURL)&&startsWith(G.reviewURL,'https://github.com/mfs9697/NewMetacomp/'), ...
 UN,'GO_M5_X6 decision or review proof is absent or invalid.');
au=C.plan.authorization;
assert(ischar(G.campaignScope)&&strcmp(G.campaignScope,'M5_X6_S4_B9_CROSSED_MAX6')&& ...
 ischar(G.approvedRunName)&&~isempty(regexp(G.approvedRunName,'^run_[a-zA-Z0-9_]+$','once'))&& ...
 ~any(strcmp(G.approvedRunName,cellstr(au.forbiddenRunNames)))&& ...
 ischar(G.campaignId)&&~isempty(regexp(G.campaignId,'^[A-Za-z0-9_-]{3,64}$','once'))&& ...
 ~any(strcmp(G.campaignId,cellstr(au.forbiddenCampaignIds))), ...
 UN,'M5-X6 campaign scope, run name or campaign ID is invalid.');
cf=G.approvedConfigurations;
assert((iscellstr(cf)||isstring(cf))&&isequal(reshape(cellstr(cf),1,[]),{'X6-01','X6-02','X6-03','X6-04','X6-05','X6-06'})&& ...
 isnumeric(G.maxSolves)&&isscalar(G.maxSolves)&&G.maxSolves==6&&isequal(G.revocationRequired,true), ...
 UN,'GO_M5_X6 must list exactly the six configurations, a six-solve ceiling and revocation.');
assert(strcmpi(G.approvedPlanSHA256,C.planSHA256)&&strcmpi(G.approvedA1SourceSHA256,C.a1SourceSHA256)&& ...
 strcmpi(G.approvedX6SourceSHA256,C.x6SourceSHA256)&&strcmpi(G.approvedMeshManifestSHA256,C.meshManifestSHA256)&& ...
 ischar(G.approvedToken)&&strcmp(G.approvedToken,C.token), ...
 SRC,'GO_M5_X6 does not bind the exact plan, sources, mesh manifest and token.');
f=G.contractEvidenceFile;
assert(ischar(f)&&startsWith(f,au.contractEvidenceDir)&&isempty(strfind(f,'..'))&& ...
 ~isempty(regexp(f,'^[A-Za-z0-9_./-]+$','once')),SRC,'M5-X6 contract evidence path is not pinned.');
E=loadContract(f);
assert(isstruct(E)&&isscalar(E)&&isfield(E,'exists')&&isequal(E.exists,true)&&ischar(E.sha256)&& ...
 ischar(G.contractEvidenceSHA256)&&strcmpi(E.sha256,G.contractEvidenceSHA256), ...
 SRC,'M5-X6 contract evidence bytes are absent or changed.');
T=jsondecode(E.text);
need={'pass','passed','total','physicalSolves','negativeTestsPassed','token'};
assert(isstruct(T)&&all(isfield(T,need)),UN,'M5-X6 contract evidence lacks required fields.');
assert(isequal(T.pass,true)&&T.passed==T.total&&T.total>=30&&T.physicalSolves==0&&isequal(T.negativeTestsPassed,true), ...
 UN,'M5-X6 contract qualification has not passed.');
assert(ischar(T.token)&&strcmp(T.token,C.token),SRC,'M5-X6 contract evidence was produced for another token.');
end
