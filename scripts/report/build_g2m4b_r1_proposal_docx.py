def sci(x, nd=1, sign=False):
    if x == 0:
        return '0'
    s = f"{x:+.{nd}e}" if sign else f"{x:.{nd}e}"
    m, e = s.split('e')
    return m.replace('-', '−').replace('.', ',') + '·10' + str(int(e)).translate(SUP)
