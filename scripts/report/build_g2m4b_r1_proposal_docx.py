def md(t):
    for a, b in REPL:
        t = re.sub(a, b, t)
    return t
def rich(p, t, size=None, bold=False, italic=False):
    for part in re.split(r'([_^]\{[^}]*\})', md(t)):
        if not part:
            continue
        if part[:2] in ('_{', '^{'):
            run = p.add_run(part[2:-1])
            run.font.subscript = part[0] == '_'
            run.font.superscript = part[0] == '^'
        else:
            run = p.add_run(part)
        if bold:
            run.bold = True
        if italic:
            run.italic = True
        if size:
            run.font.size = Pt(size)
    return p
