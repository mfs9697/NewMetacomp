# -*- coding: utf-8 -*-
"""Chapter 5: influence of the material architecture on the crack driving force (S0-S8)."""
import os
from common import c, sg, sci, pct, CASES, ARCH


def ch5(R, D, FIG):
    P, H, EQ = R.P, R.H, R.EQ
    L = D['LP2A']
    M2, M3 = D.csv('M2'), D.csv('M3')
    H(1, 'Вплив матеріальної архітектури на рушійну силу руйнування', key='arch')

    # ------------------------------------------------------------------ 5.1
    H(2, 'Перші результати: три однакові кільця', key='first')
    P('Перший матеріальний розрахунок (етап WP-M, 19.11.2026) ставив найпростіше питання: чи змінює рушійну силу '
      'ідеально зв’язане кільце навколо кожного отвору, якщо геометрія тріщини, сітка, опори і навантаження ті самі? '
      'На замороженій тріщині стану S2 однорідної пластини порівняно чотири варіанти: однорідний розрахунок старим '
      'розв’язувачем, контрольний розрахунок новим двофазним розв’язувачем з $\\lambda$ = 1 (побітово тотожний першому), '
      'три м’які кільця ($\\lambda$ = 0,5) і три жорсткі ($\\lambda$ = 2). Двофазний розв’язувач попередньо перевірено на '
      'точному розв’язку для отвору з покриттям (14 перевірок з 14).')
    s2 = {r['case']: r for r in M2 if r['state'] == 'S2'}
    soft = [r for r in M2 if r['case'].lower().endswith('soft')]
    stiff = [r for r in M2 if r['case'].lower().endswith('stiff')]
    P(f"Результат: три м’які кільця *збільшують* $G$ на {pct(float(soft[2]['R_EDI'])-1,2)} %, три жорсткі *зменшують* на "
      f"{pct(1-float(stiff[2]['R_EDI']),2,False)} %. Ефект майже повністю припадає на моду I. За основним правилом "
      'оцінювання він розрізнений із запасом у кілька порядків, за консервативним (±3,5 %) — ні; ця розбіжність двох '
      'правил супроводжує все дослідження (підрозділ [[sec:v_soft2]]).')
    P('Етап M2 (21.11.2026) повторив порівняння на трьох заморожених положеннях тріщини однорідної пластини '
      '([[tab:m2]]). Виявилося два факти, які визначили подальший напрям. По-перше, для м’яких кілець **знак ефекту '
      'змінюється**: у стані S0 вони екранують вершину, а в S1 і S2 — підсилюють рушійну силу. По-друге, зміна '
      'податливості пластини при цьому практично стала (м’які кільця +1,45 %, жорсткі −1,05–1,06 % у всіх трьох '
      'станах), тобто ефект у вершині залежить від положення тріщини відносно кілець, а не від загальної жорсткості '
      'конструкції; жодна глобальна характеристика жорсткості не замінює локальної величини.')
    rows = []
    for st in ('S0', 'S1', 'S2'):
        a = [r for r in soft if r['state'] == st][0]
        b = [r for r in stiff if r['state'] == st][0]
        rows.append([st, c(float(a['s_mm']), 1), pct(float(a['R_EDI']) - 1, 2), sg(float(a['dTheta_deg']), 3),
                     pct(float(b['R_EDI']) - 1, 2), sg(float(b['dTheta_deg']), 3)])
    R.TAB('m2', 'Прямий ефект трьох однакових кілець на замороженій тріщині однорідної пластини (етап M2): зміна $G$ і '
                'зміна локального кута МКН',
          ['Стан', '$s$, мм', 'м’які: $G/\\GH-1$, %', 'м’які: $\\Delta\\theta$, °', 'жорсткі: $G/\\GH-1$, %',
           'жорсткі: $\\Delta\\theta$, °'], rows, widths=[1.6, 1.8, 3.4, 3.0, 3.4, 3.0], size=10)
    m3 = {(r['material'], r['s_mm']): r for r in M3}
    P('Етап M3 дозволив тріщині йти власним шляхом у пластинах з м’якими і жорсткими кільцями (два кроки по 4 мм) і '
      'вперше відокремив прямий ефект від траєкторного: відношення $G$ на власній траєкторії до $G$ того самого '
      'матеріалу на траєкторії однорідної пластини в стані S2 дорівнює ' +
      f"{c(float(m3[('soft','33.4')]['R_path']),6)} для м’яких кілець і {c(float(m3[('stiff','33.4')]['R_path']),6)} "
      'для жорстких. Траєкторний ефект, отже, на порядок-два менший від прямого і *протилежний* йому за знаком. '
      'Бічне зміщення вершини відносно однорідної траєкторії в S2 — +0,0905 мм (м’які) і −0,0602 мм (жорсткі); '
      'різниця напрямку виникає на першому кроці (+0,65° і −0,42°), а далі локальні кути майже збігаються з '
      'однорідними. Етап M4.A повторив усі три двокрокові ланцюжки на незалежно побудованому сімействі зовнішніх '
      'сіток зі 112-кутними межами кілець: усі зміщення і відношення зберегли знак і величину (зміна прямого ефекту '
      'до 2·10⁻⁵). Рецензія прийняла цей результат з обов’язковим обмеженням: ядро біля вершини, комір і область '
      'інтегрування в обох сімействах спільні, тому перевірено чутливість до зовнішньої сітки і дискретизації меж '
      'кілець, але не до сітки біля вершини.')

    # ------------------------------------------------------------------ 5.2
    H(2, 'Вибір чотирьох основних конфігурацій', key='choice')
    P('Сумарний ефект трьох однакових кілець виявився малою різницею великих внесків протилежних знаків. Це показав '
      'етап M4.B, у якому на замороженій тріщині S2 розраховано всі вісім комбінацій активних кілець для кожного з двох '
      'контрастів (докладно — підрозділ [[sec:m4b]]): одне м’яке кільце змінює $G$ на +4,43 %, −3,63 % або +2,33 % '
      'залежно від того, яке саме кільце активне, тоді як усі три разом дають лише +2,18 %. За однакової площі '
      'зміненого матеріалу розміщення змінює знак ефекту.')
    P('За цими результатами для розрахунку довших траєкторій дослідник обрав три архітектури, що представляють якісно '
      'різні поєднання ефектів у стані S2 ([[tab:choice]]), і однорідну пластину H як базу порівняння. Обрані '
      'конфігурації — *контрастні попередні гіпотези, а не ранжовані оптимальні рішення*: вони мають різну площу '
      'активного матеріалу (2024,3 мм² у stiff13 проти 1012,2 мм² у soft2 і soft1), а значення кутів у таблиці '
      'стосуються лише локального базису замороженого стану S2 і не є прогнозом траєкторії.')
    R.TAB('choice', 'Три архітектури, обрані для траєкторних розрахунків, та їх характеристики на замороженій тріщині S2 '
                    'однорідної пластини (M4.B)',
          ['Конфігурація', 'Активні кільця', '$\\lambda$', '$\\FG$, %', '$\\Delta\\theta$, °', 'Чому обрано'], [
              ['stiff13', '1 і 3', '2', '−5,48', '−0,81', 'найбільше екранування серед розрахованих випадків; поворот у бік кілець'],
              ['soft2', '2', '0,5', '−3,63', '−0,37', 'екранування за малої зміни напрямку (це не означає «обхід» кілець)'],
              ['soft1', '1', '0,5', '+4,43', '+1,31', 'найбільший поворот від кілець, але з підсиленням рушійної сили'],
          ], widths=[2.8, 2.1, 1.1, 1.7, 1.9, 6.9], size=9.5, align='lcccc' + 'l')

    # ------------------------------------------------------------------ 5.3
    H(2, 'Контраст на власних траєкторіях і умова однакової довжини тріщини', key='fgdef')
    P('Для траєкторних розрахунків основною енергетичною величиною є контраст на власних траєкторіях')
    EQ(r'\FG(s)=\frac{\GX(s)}{\GH(s)}-1,', key='FG')
    P('де $\\GX(s)$ — швидкість вивільнення енергії в конфігурації $X$ на *її власній* траєкторії за довжини тріщини $s$, '
      '$\\GH(s)$ — те саме для однорідної пластини. Порівняння коректне лише за однакової довжини $s$ з двох причин. '
      'По-перше, $G$ сама швидко зростає з довжиною тріщини (на 3–4 % на міліметр), тому порівняння станів з різними '
      'довжинами дало б контраст, який відображає довжину, а не архітектуру. По-друге, лише за однакових довжини, '
      'навантаження, товщини й опор обидва значення належать до порівнянних крайових задач. У дослідженні ця умова '
      'виконується за побудовою: усі траєкторії починаються зі спільної тріщини S0 і мають однакові прирости по 4 мм, '
      'тому однаковий номер стану означає однакову довжину; аналіз відмовляється обчислювати контраст для станів, '
      'прийнятих лише в одному з ланцюжків.', indent=False)
    P('Контраст $\\FG$ — це *повний* ефект: він містить і пряму дію матеріалу, і наслідок іншої траєкторії. Лише у стані '
      'S0, де геометрія спільна, він збігається з прямим матеріальним ефектом (розділ [[sec:x6]]).')

    # ------------------------------------------------------------------ 5.4
    H(2, 'Еволюція екранування і підсилення від S0 до S8', key='evol')
    P('Стани S0–S4 отримано в кампанії LP1 і побітово відтворено в A0; стани S5–S8 — у кампанії LP2-A1 (25.11.2026, '
      '16 розв’язків, жодної зупинки; докладніше — розділ [[sec:paths]]). Усі 36 станів розраховано на одному сімействі '
      'сіток за однаковими критеріями прийняття. Контраст наведено в [[tab:FG]] і на [[fig:GFG]], б.')
    rows = []
    for n in range(9):
        rows.append([f'S{n}', c(L['stiff13']['s_mm'][n], 1)] + [pct(L[x]['F_G'][n], 3) for x in ARCH])
    R.TAB('FG', 'Контраст швидкості вивільнення енергії на власних траєкторіях $\\FG$, %', ['Стан', '$s$, мм'] + ARCH, rows,
          widths=[1.8, 2.2, 3.4, 3.4, 3.4], size=10, align='ccccc')
    f = {x: L[x]['F_G'] for x in ARCH}
    P('Три архітектури поводяться по-різному.')
    R.BUL([
        f"**stiff13: екранування посилюється** — від {pct(f['stiff13'][0],2)} % у S0 до {pct(f['stiff13'][4],2)} % у S4 і "
        f"{pct(f['stiff13'][8],2)} % у S8, монотонно на кожному кроці.",
        f"**soft2: екранування слабшає** — від {pct(f['soft2'][0],2)} % до {pct(f['soft2'][4],2)} % і {pct(f['soft2'][8],2)} %, "
        'також монотонно; знак у межах S0–S8 не змінюється.',
        f"**soft1: підсилення зростає** — від {pct(f['soft1'][0],2)} % до {pct(f['soft1'][4],2)} % і {pct(f['soft1'][8],2)} %.",
    ])
    P('Гіпотези H1 (посилення екранування stiff13) і H2 (послаблення екранування soft2), зафіксовані перед кампанією '
      'LP2-A1, підтримано як *обчислені монотонні тенденції*; це не твердження з сертифікованою похибкою дискретизації. '
      'Класифікація soft2 за консервативним правилом залишається «нерозрізнено» (підрозділ [[sec:v_soft2]]). Лінійне '
      'продовження тенденції soft2 до нуля поблизу $s$ ≈ 73 мм є неперевіреною числовою екстраполяцією, а не '
      'геометричним чи механічним передбаченням.')
    R.FIG('GFG', os.path.join(FIG, 'F08_3_G_FG.png'),
          '(а) Абсолютна швидкість вивільнення енергії $G$ на власних траєкторіях за $P$ = 1 Н; (б) відносний контраст '
          '$\\FG$. Вертикальна пунктирна лінія — межа між кампаніями LP1/A0 (S0–S4) і LP2-A1 (S5–S8).', width=16.0)

    # ------------------------------------------------------------------ 5.5
    H(2, 'Відносний контраст і абсолютна рушійна сила', key='abs')
    G = {x: L['states'][x]['G'] for x in CASES}
    rows = []
    for x in CASES:
        rows.append([x, c(G[x][0] * 1e8, 4), c(G[x][4] * 1e8, 4), c(G[x][8] * 1e8, 4),
                     c(100 * (G[x][8] / G[x][4] - 1), 2), c(G[x][8] / G[x][0], 3)])
    R.TAB('Gabs', 'Абсолютна швидкість вивільнення енергії $G\\cdot 10^{8}$, Н/мм ($P$ = 1 Н), та її зростання',
          ['Конфігурація', 'S0', 'S4', 'S8', 'зростання S4→S8, %', '$G(S_{8})/G(S_{0})$'], rows,
          widths=[3.0, 2.4, 2.4, 2.4, 3.4, 3.0], size=10)
    P('Контраст $\\FG$ — відносна величина, і його не можна читати як зменшення рушійної сили. Абсолютна $G$ '
      '**зростає в усіх чотирьох конфігураціях** ([[tab:Gabs]], [[fig:GFG]], а): за сталої сили від S4 до S8 — на ' +
      ', '.join(f"{c(100*(G[x][8]/G[x][4]-1),2)} % ({x})" for x in CASES) +
      '. У stiff13, де відносне екранування найсильніше, рушійна сила у стані S8 все одно в ' +
      f"{c(G['stiff13'][8]/G['stiff13'][0],2)} раза більша, ніж у S0. У стані S8 значення $G$ для soft1 перевищує значення "
      f"для stiff13 на {c(100*(G['soft1'][8]/G['stiff13'][8]-1),2)} % за однакової довжини тріщини (на різних власних "
      'траєкторіях).')
    P('Отже, екранування в цьому дослідженні означає: *за тієї самої сили і тієї самої довжини тріщини рушійна сила '
      'менша, ніж в однорідній пластині*. Воно не означає ні зменшення рушійної сили з ростом тріщини, ні стійкого '
      'росту, ні зупинки. Питання про стійкість росту і можливість зупинки потребує критерію опору матеріалу та '
      'режиму навантаження, яких модель не містить, і в цьому звіті не розглядається. Енергетичний ефект архітектури в цих умовах еквівалентний зсуву '
      'довжини тріщини: у стані S4 — близько −2,2 мм (stiff13), −0,9 мм (soft2) і +1,8 мм (soft1); це локальне '
      'енергетичне порівняння, а не відстань до зупинки.')
