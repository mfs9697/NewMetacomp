# -*- coding: utf-8 -*-
"""Chapter 6: mechanical causes of shielding and amplification (M4.B, R1, then M5 and G1)."""
import os
from common import c, sg, sci, pct
from ch06_m5g1 import m5g1


def ch6(R, D, FIG):
    P, H, EQ = R.P, R.H, R.EQ
    CS, DEC, R1 = D.csv('M4B_CASES'), D.csv('M4B_DEC'), D.csv('R1')
    H(1, 'Механічні причини екранування та підсилення', key='mech')
    P('Розділ послідовно відповідає на три питання. Який внесок у зміну рушійної сили дає кожне кільце окремо і чи '
      'складаються ці внески (етап M4.B з перевіркою R1)? Яка частина ефекту на власній траєкторії є прямою дією '
      'матеріалу (меморандум M5)? З якими властивостями пружних полів однорідної пластини пов’язані знаки внесків '
      'кілець (дослідження G1)? У кожному підрозділі розмежовано безпосередні числові спостереження, алгебраїчні '
      'тотожності та запропоновані механічні тлумачення.')

    # ------------------------------------------------------------------ M4.B
    H(2, 'Внески окремих кілець на замороженій тріщині (M4.B)', key='m4b')
    P('Розрахунок M4.B виконано на одній замороженій геометрії — тріщині стану S2 однорідної пластини — і на одній '
      'сітці; змінювалося лише те, які кільця активні. Для кожного з двох контрастів ($\\lambda$ = 0,5 і 2) розраховано '
      'всі $2^{3}=8$ комбінацій; випадок без активних кілець спільний, тому розв’язків 15. Контрольні випадки '
      '(жодного кільця; усі три) побітово збіглися з попередніми розрахунками. Для множини активних кілець $S$ '
      'означено')
    EQ(r'\FG(S)=\frac{G(S)}{G(\varnothing)}-1,\quad F_{\theta}(S)=\theta(S)-\theta(\varnothing),', key='FS')
    P('внески окремих кілець $f_{i}=F(\\{i\\})$ і взаємодії', indent=False)
    EQ(r'I_{ij}=F(\{i,j\})-f_{i}-f_{j},\quad I_{123}=F(\{1,2,3\})-\sum_{i}f_{i}-\sum_{i<j}I_{ij}.', key='Iij')
    P('Це точний алгебраїчний розклад, який не потребує припущення про адитивність. Величини $\\FG$ і $F_{\\theta}$ мають '
      'різну природу і ніколи не поєднуються в один показник.', indent=False)
    by = {(r['contrast'], r['bits']): r for r in CS}
    names = {'100': '{1}', '010': '{2}', '001': '{3}', '110': '{1, 2}', '101': '{1, 3}', '011': '{2, 3}', '111': '{1, 2, 3}'}
    rows = []
    for bits in ('100', '010', '001', '110', '101', '011', '111'):
        a, b = by[('0.5', bits)], by[('2', bits)]
        rows.append([names[bits], pct(float(a['F_G']), 3), sg(float(a['F_theta_deg']), 3),
                     pct(float(b['F_G']), 3), sg(float(b['F_theta_deg']), 3)])
    R.TAB('m4b', 'Прямий ефект кожної комбінації активних кілець на замороженій тріщині S2 однорідної пластини: зміна '
                 'швидкості вивільнення енергії $\\FG$ і локального кута МКН $F_{\\theta}$ (додатний кут — поворот від '
                 'стовпця отворів)',
          ['Активні кільця', 'м’які: $\\FG$, %', 'м’які: $F_{\\theta}$, °', 'жорсткі: $\\FG$, %', 'жорсткі: $F_{\\theta}$, °'],
          rows, widths=[3.2, 3.3, 3.3, 3.3, 3.3], size=10)
    R.FIG('m4bbars', os.path.join(FIG, 'F06_1_vnesky_kilets.png'),
          'Внески окремих кілець на замороженій тріщині S2: (а) зміна швидкості вивільнення енергії; (б) зміна '
          'локального кута МКН. Блакитні стовпці — м’яке кільце ($\\lambda$ = 0,5), червонуваті — жорстке ($\\lambda$ = 2); '
          'праворуч для порівняння — усі три кільця разом.', width=16.0)
    f3s = float(by[('2', '001')]['F_G'])
    P('Із [[tab:m4b]] і [[fig:m4bbars]] випливають такі спостереження.')
    R.BUL([
        '**Знак ефекту залежить від положення кільця.** М’яке кільце 1 підсилює рушійну силу (+4,43 %), м’яке кільце 2 '
        'екранує (−3,63 %), м’яке кільце 3 знову підсилює (+2,33 %). Для жорстких кілець знаки протилежні: −3,65 %, '
        f"+3,04 % і {pct(f3s,2)} %. Кільце 2 діє протилежно кільцям 1 і 3 за обох контрастів.",
        '**Близькість до вершини не є визначальною для енергії.** Кільце 3, віддалене від вершини на 147 мм, змінює $G$ '
        'на 2 %, а знаки чергуються від кільця до кільця.',
        '**Сумарний ефект трьох кілець — мала різниця великих внесків**: для м’яких +4,43 − 3,63 + 2,33 = +3,13 %, а з '
        'урахуванням взаємодій (разом −0,95 %) отримуємо +2,18 %.',
        '**Для кута порядок інший.** Найбільше на локальний кут впливає найближче кільце 1 (+1,31° для м’якого, −1,11° '
        'для жорсткого); кільця 2 і 3 впливають у 3,5–3,8 раза слабше, майже однаково і з протилежним знаком. Знакові '
        'закономірності для енергії (кільце 2 проти 1 і 3) і для кута (кільце 1 проти 2 і 3) різні.',
    ])
    P('Пояснення до значення для жорсткого кільця 3. Незаокруглене значення дорівнює ' + sg(100 * f3s, 4) + ' %, тобто '
      '−1,82 %. У початковому тексті результатів M4.B, в описі відповідного запиту на злиття і в меморандумі M5 воно '
      'наведене як −1,83 %; це похибка заокруглення, яку виправлено в цьому звіті (додаток А, запис К-14). Вихідні '
      'записи не змінювалися.')
    P('**Статус гіпотез етапу.** Гіпотезу про неоднаковий вплив кілець підтримано. Гіпотезу про те, що порядок '
      'важливості кілець за енергією і за кутом різний, за попередньо зафіксованим правилом (порівняння модулів) '
      '*відхилено*: за модулем в обох випадках $|f_{1}|>|f_{2}|>|f_{3}|$, хоча знакові закономірності різні. '
      'Взаємодії кілець за основним правилом відмінні від нуля, за консервативним — ні.')
    i12 = [r for r in DEC if r['observable'] == 'F_G' and r['term'] == 'I_12']
    P('**Про взаємодії.** Парні взаємодії для енергії становлять від −1,4·10⁻⁵ до −4,9·10⁻³ (у частках), потрійна — '
      '−7,3·10⁻⁴ (м’які) і +3,1·10⁻⁴ (жорсткі). За рішенням рецензії всі вони є *числовими членами розкладу, розрізненими лише за основним '
      'правилом, а не незалежно встановленими фізичними взаємодіями*; найменші з них ($I_{13}$, $I_{123}$) мають той '
      'самий порядок, що й зміна результатів між сімействами сіток, і не тлумачаться. Єдиний кандидат на стійку '
      'взаємодію за обома правилами — взаємодія кілець 1 і 2 в куті (+0,12° для м’яких).')
    P('**Перевірка R1.** Щоб з’ясувати, чи не є знакозмінність наслідком дискретизації, шість випадків з одним активним '
      'кільцем і випадок жорстких кілець 1 і 3 повторено на незалежно побудованій сітці з тією самою тріщиною '
      '(112-кутні межі кілець, 35 125 трикутників проти 28 625). Усі ефекти зберегли знак; зміна не перевищує 0,08 % '
      'від величини кожного ефекту (наприклад, для жорстких кілець 1 і 3: −5,4780 % → −5,4810 %); порядок кілець за '
      'обома величинами не змінився. Обмеження ті самі, що й для M4.A: ядро біля вершини спільне, взаємодії не '
      'перевірялися. Перевірка також показала, що для $\\FG$ зміна між сімействами сіток (1–3·10⁻⁵) у 10–100 разів '
      'перевищує оцінку за основним правилом (≈ 10⁻⁶): жодна з двох оцінок невизначеності не є строгою межею похибки.')
    P('**Чого M4.B не встановлює.** Розрахунок виконано для однієї геометрії тріщини; він нічого не говорить про '
      'траєкторію. Формулювання «розміщення важливіше за кількість» і «найкраща архітектура» рецензія замінила '
      'точнішим: *за однакової площі активного матеріалу розміщення істотно змінює числову реакцію в замороженому '
      'стані S2; серед розрахованих випадків жорсткі кільця 1 і 3 мають найменше значення* $\\FG$. Порівняння з '
      'випадками іншої площі не є порівнянням рівноцінних рішень. Карти густини енергії показують перерозподіл по '
      'всьому навантаженому перерізу, що узгоджується з впливом через глобальну передачу навантаження, але це '
      'прочитання полів, а не відокремлений механізм.')

    m5g1(R, D, FIG)

    H(2, 'Підсумок: що підтверджено безпосередньо і що є тлумаченням', key='mechsum')
    R.TAB('mechsum', 'Статус тверджень про механічні причини ефектів',
          ['Твердження', 'Статус'], [
              ['Знак і величина внеску кожного кільця в $G$ і в локальний кут у стані S2',
               'числове спостереження; відтворено на незалежній зовнішній сітці'],
              ['Повний ефект у стані S0 є прямим матеріальним', 'точно (спільні геометрія і сітка)'],
              ['Розклад на внески кілець і взаємодії', 'алгебраїчна тотожність; малі взаємодії фізично не тлумачаться'],
              ['Знак ефекту кільця визначається знаком похідної енергії в його області за довжиною тріщини',
               'енергетична оцінка першого порядку; знак підтверджено в усіх порівняннях, величина — з відхиленням 14–32 %'],
              ['Відхилення від оцінки першого порядку є «членами другого порядку»',
               '**не підтверджено**: це поправки скінченного контрасту, члени другого порядку не виводилися'],
              ['Область кільця 2 «стиснута в обох напрямках»', '**спростовано** збереженими даними: стан змішаний з переважанням стиску'],
              ['Особлива роль лінії «опора — сила»; «розвантаження діагонального розпору»',
               'гіпотеза; лінія — геометричний орієнтир, підтверджений лише частково'],
              ['Знак $\\FG$ збігається зі знаком зміни податливості', 'енергетичне тлумачення, узгоджене з розрахунками; не незалежний доказ'],
              ['Єдиний механізм передачі навантаження', '**не встановлено**'],
          ], widths=[9.0, 7.5], size=9.5, align='ll')
