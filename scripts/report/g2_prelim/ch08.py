def _j(D, *parts):
    with open(os.path.join(D.repo, *parts), encoding='utf-8-sig') as f:
        return json.load(f)


def ch8(R, D, FIG):
    P, H, EQ = R.P, R.H, R.EQ
    L = D['LP2A']
    ST = L['states']
    CALLS = D['LP2A_CALLS']
    VER = _j(D, *CAMP, 'LP2A_VERIFY_ONLY.json')
    ARCREC = _j(D, *CAMP, 'LP2A_ARCHIVE_RECORD.json')
    GEO = _j(D, 'docs', 'research', 'G2_LP2_evidence', 'LP2_S5_GEOMETRY.json')
    SCAN = _j(D, 'docs', 'research', 'G2_LP2_evidence', 'LP2_MESH_SCAN.json')
    PROBE = _j(D, 'docs', 'research', 'G2_LP2_evidence', 'LP2_MESH_PROBE.json')
    A1 = D['A1']
    NC = VER['numericalChecks']

    # ---- derived series (all from LP2A_ANALYSIS.json)
    F = {x: [100 * v for v in L[x]['F_G']] for x in ARCH}
    d = {x: L[x]['d_mm'] for x in ARCH}
    dphi = {x: L[x]['dHeading_deg'] for x in ARCH}
    dth = {x: L[x]['dMTS_deg'] for x in ARCH}
    dphi9 = {x: dphi[x][8] + dth[x][8] for x in ARCH}                  # kinematic identity, no solve at S9
    G = {x: ST[x]['G'] for x in CASES}
    cand = {x: ST[x]['terminal']['candidate'] for x in CASES}
    term = {x: ST[x]['terminal'] for x in CASES}
    assert all(term[x]['classification'] == 'CAMPAIGN_LIMIT_REACHED' and term[x]['interfaceEncounter'] is False and
               term[x]['physicalArrest'] is False and term[x]['truncatedByCeiling'] is True for x in CASES)
    assert all(cand[x]['classification'] == 'MATRIX_ADVANCE' and not cand[x]['constraints'] for x in CASES)
    assert len(NC) == 16 and all(t['pass'] and t['sifCriteria'] == '16/16' for t in NC)
    # cross-check of the S9 predictor against the headings of the stored candidate polylines
    def head_last(x):
        p = cand[x]['polyline_mm']
        return math.degrees(math.atan2(p[-1][1] - p[-2][1], p[-1][0] - p[-2][0]))
    for x in ARCH:
        assert abs((head_last(x) - head_last('H')) - dphi9[x]) < 1e-5, 'S9 predictor mismatch'

    H(1, 'Еволюція траєкторій тріщини в матриці: стани S0–S8', key='paths')
    P('У розділах [[sec:arch]] і [[sec:x6]] чотири конфігурації — однорідну пластину H та архітектури stiff13, soft2 і '
      'soft1 — порівняно на коротких ділянках траєкторії. Тут простежено, як їхні траєкторії та рушійна сила руйнування '
      'змінюються під час подальшого росту тріщини в матриці від довжини 25,4 мм (стан S0) до 57,4 мм (стан S8). Стани '
      'S0–S4 розраховано в кампанії LP1 і побітово відтворено в A0 (підрозділ [[sec:v_lp1]]); стани S5–S8 — у кампанії '
      'LP2-A1, виконаній 25.11.2026 за письмовим дозволом дослідника. Незалежна рецензія 6056658077 прийняла LP2-A1 як '
      '*завершену обмежену числову кампанію побудови траєкторій*; її уточнення до первинного звіту кампанії враховано в '
      'цьому розділі повністю.')
    P('Траєкторії є умовними розрахунковими продовженнями лінійної механіки руйнування за критерієм максимальних колових '
      'напружень [[cite:erdogan1963]] для одиничної сили $P$ = 1 Н. Критерію опору руйнуванню в моделі немає, тому '
      'розрахунок не стверджує ні того, що тріщина справді росте, ні за якого навантаження, ні де вона зупиняється '
      '(підрозділ [[sec:four]]). Усі тлумачення нижче стосуються лише цих числових траєкторій.')

    # ------------------------------------------------------------------ 8.1
    H(2, 'Питання, яке ставить розділ', key='p_question')
    P('Розділ [[sec:x6]] установив, що в стані S4 власна траєкторія майже повністю компенсує дію матеріалу на *локальний '
      'приріст* кута МКН, але лише на кілька відсотків — його дію на рушійну силу. Це твердження про один стан. '
      'Кампанія LP2-A1 ставила питання про *еволюцію*: коли тріщина росте далі, чи накопичуються початкові відмінності '
      'напрямку між архітектурами, чи вони взаємно скорочуються, чи змінюють знак; як при цьому змінюються енергетичний '
      'ефект і геометричні ознаки траєкторій; і чи наближається вершина до якоїсь межі розрахункової області. Щоб не '
      'змішувати відповіді, у кампанії розрізнено шість величин:')
    R.BUL([
        'екранування чи підсилення рушійної сили — контраст $\\FG$ ([[eq:FG]]);',
        'зміна локального напрямку — приріст кута МКН $\\theta_{n}$ ([[eq:mtsroot]]);',
        'накопичена різниця траєкторій — відносний курс $\\Delta\\varphi_{n}$ і знакове бічне зміщення $d_{n}$ '
        '(підрозділ [[sec:derived]]);',
        'наближення до *активної* межі кільця, тобто до реального матеріального розриву;',
        'наближення до отвору чи до зовнішнього краю пластини;',
        '*числове* припинення розрахунку — через обмеження сітки, захисної області чи межу кампанії; воно ніколи не '
        'тлумачиться як фізична зупинка тріщини.',
    ])

    # ------------------------------------------------------------------ 8.2
    H(2, 'Постановка кампанії LP2-A1', key='p_design')
    b = [r['B9minusB0'] for r in GEO['rows']]
    dth_b = [abs(r['MTS_deg']) for r in b]
    dtip_b = [r['tipDistance_mm'] for r in b]
    P('Початковими є прийняті стани S4 з відтворення A0; вони побітово збігаються з первинними станами LP1, а формула '
      'продовження, застосована до батьківських станів A0, побітово відтворює S1–S4 усіх чотирьох траєкторій. '
      'Батьківські значення КІН узято саме з A0, тобто із сімейства сіток, на якому перевірено алгоритм поширення. '
      'Подрібнення сітки біля вершини в дослідженні A1 (підрозділ [[sec:v_a1]]) змінює кут МКН у стані S4 на ' +
      f"{sci(min(dth_b), 2)}–{sci(max(dth_b), 2)}°, а вершину S5 — на {sci(min(dtip_b), 2)}–{sci(max(dtip_b), 2)} мм, "
      'тому сімейство сіток під час продовження не змінювали.')
    P('Не змінювалося нічого, крім довжини ланцюжка: плоский напружений стан і сітки з елементами T6, ідеальне зчеплення '
      'фаз, шарнір, каток і сила 1 Н; сліпа оцінка за розкриттям берегів і знаковий EDI на п’яти областях; усі 16 '
      'критеріїв прийняття ([[tab:gates]]); крок 4 мм; захищене ядро біля вершини з коміром 3,3 мм; напрямна область '
      '15 мм; аудит сітки з 34 перевірок; бюджет 40 000 трикутників; сам генератор сіток (підрозділ [[sec:mesh]]). Нового '
      'лише те, що кожен стан додатково записує відстані до всіх кілець, отворів і країв, запаси напрямної області '
      'та завершальну класифікацію.')
    P('Межі кампанії зафіксовано наперед у політиці (хеш `093a546b…`): стани S5–S8 кожного з чотирьох випадків, не '
      'більше 16 розв’язків (4 × 4), порядок H, stiff13, soft2, soft1, крок не адаптується, повторів немає, а допущена '
      'невдала спроба витрачає бюджет. Ще до кампанії, без жодного пружного розв’язку, перевірено, що чотири '
      'геометричні кандидати S5 допустимі (усі `MATRIX_ADVANCE`) і що відповідні сітки (' +
      f"{thou(min(r['T3'] for r in PROBE['rows'] if r['probe'] == 'S5_candidate'))}–"
      f"{thou(max(r['T3'] for r in PROBE['rows'] if r['probe'] == 'S5_candidate'))} трикутників) проходять аудит "
      '34 з 34.')
    P('За підсумком кожного випадку присвоюється одна з завершальних міток:', indent=False, keep=True)
    R.BUL([
        '`MATRIX_ADVANCE` — кандидат наступного стану проходить усі перевірки;',
        '`INTERFACE_APPROACH` — порушено перевірку, пов’язану з *активним* кільцем (напрямна область, область '
        'інтегрування чи відступ відрізка);',
        '`INTERFACE_ENCOUNTER` — у LP2-A1 не призначається ніколи, бо потребувала б прийнятого стану, що реально '
        'досягає межі; екстрапольований перетин відрізка-кандидата є лише наближенням;',
        '`HOLE_BOUNDARY_APPROACH`, `EXTERNAL_BOUNDARY_APPROACH` — наближення до отвору чи до краю пластини;',
        '`NUMERICAL_HOLD` — пасивний контур кільця, самоперетин, сітка, аудит, КІН, МКН, записи, пам’ять;',
        '`CAMPAIGN_LIMIT_REACHED` — прийнято стан S8, межу кампанії досягнуто.',
    ])
    P('Пріоритет за одночасного порушення кількох перевірок: `INTERFACE_APPROACH` > `HOLE_BOUNDARY_APPROACH` > '
      '`EXTERNAL_BOUNDARY_APPROACH` > `NUMERICAL_HOLD`. Збої поділено на чотири класи: *локальний* (сітка, аудит, розв’язувач, '
      'критерії КІН, корінь МКН, запаси) завершує лише цей випадок міткою `NUMERICAL_HOLD`, а решта випадків може '
      'продовжуватися; *глобальний* і *передопускний* (джерела, політика, дозвіл, цілісність записів чи журналу, '
      'пам’ять) зупиняють кампанію без закриття; *відмова кампанії* нічого не записує.')
    P('Напередодні дозволу рецензія 6055250219 визнала наукову постановку прийнятною, але вимагала чотирьох вузьких '
      'виправлень, виконаних без жодного нового розв’язку. C1: завершення випадку після локальної зупинки має '
      'проходити через спільне закриття кампанії. C2: повторне використання записів перевіряло лише ідентичність, тому '
      'додано верифікатор, що лише читає й перевіряє хеші сітки, фаз і розв’язку, рівність знакових КІН і рекурентність '
      'ламаної. C3: гіпотези переформульовано правилами, наведеними в [[tab:p_hyp]]. C4: повторна кваліфікація '
      '(107 перевірок із 107, жодного розв’язку, 541 захищений файл не змінено), що змінила політику й її хеш.')
    R.TAB('p_hyp', 'Наперед зафіксовані гіпотези кампанії LP2-A1 і правила їх оцінювання',
          ['Позн.', 'Формулювання', 'Правило оцінювання'], [
              ['H1', 'Екранування stiff13 ($\\FG<0$) надалі зростає за модулем',
               'Лише поки $\\FG<0$ у кожній точці S4…S$n$. `SUPPORTED`, якщо $\\FG$ строго спадає; `CONTRADICTED`, якщо '
               'останнє значення зсунулося проти гіпотези відносно першого; `MIXED` — інакше. Зміна знака — '
               '`SIGN_TRANSITION`, ніколи не посилення чи послаблення'],
              ['H2', 'Екранування soft2 надалі слабшає ($|\\FG|$ зменшується)',
               'Те саме правило; `SUPPORTED`, якщо $\\FG$ строго зростає до нуля'],
              ['H3', 'Локальна компенсація за кутом МКН, помічена в S4, зберігається поодаль від кілець, але змінюється, '
                     'коли тріщина до них наближається',
               'Лише описовий замінник (`DESCRIPTIVE_PROXY_ONLY`): $\\Delta\\theta$ подається разом з різницею курсів і '
               'бічним зміщенням; розкладу на матеріал, траєкторію й взаємодію немає, висновку про компенсацію з малих '
               'локальних різниць кутів немає'],
              ['H4', 'Матеріальний контраст змінює те, чи зустріне тріщина активну межу раніше за іншу межу',
               '`NOT_TESTABLE_WITHIN_LP2_A1`: числове наближення — не зустріч, пасивний контур — не матеріальний розрив; '
               'остання вершина, об’єкт, маска кілець, відстань, обмежувальна перевірка й обрив межею кампанії лише '
               'описуються'],
          ], widths=[1.5, 5.1, 9.8], size=9, align='clj',
          note='Рівність довжин дуги обов’язкова: аналіз відмовляється порівнювати стани, прийняті лише в одному з '
               'ланцюжків (`G2LP2:ANALYSIS_UNSUPPORTED`).')

    # ------------------------------------------------------------------ 8.3
    H(2, 'Чому кампанія зупинена на S8: сітка, а не напрямна область', key='p_limit')
    states = sorted({r['state'] for r in SCAN['rows']})
    cnt = {s: [sum(1 for r in SCAN['rows'] if r['state'] == s and r['pass']), sum(1 for r in SCAN['rows'] if r['state'] == s)]
           for s in states}
    npass = sum(v[0] for v in cnt.values())
    ntot = sum(v[1] for v in cnt.values())
    P('Рівень S8 (57,4 мм) — не результат розвитку траєкторій, а межа, яку задала кваліфікація сіток. Незмінений '
      'генератор надійний лише до десяти вершин ламаної, тобто до стану S8: далі частина сіток відхиляється перевіркою '
      '`HOLD_LIP_STATIONS` (різна кількість вузлів на двох берегах тріщини; докладно — розділ [[sec:pairing]]). Це '
      f"перевірено на {ntot} синтетичних ламаних — гіпотетичних продовженнях чотирьох траєкторій із замороженим кутом "
      f"МКН стану S4 і прямим ходом ([[tab:p_scan]]): пройшли {npass}, відхилено {ntot - npass}, і кожна з відмов — саме "
      '`HOLD_LIP_STATIONS`. Скан не є ні гарантією успіху, ні ймовірністю відмови на справжній траєкторії (рецензія '
      '6055250219); він лише обґрунтовує межу кампанії. Чотири справжні кандидати S5 пройшли окремо (4 з 4), '
      'синтетичні S6–S8 — 24 з 24.')
    R.TAB('p_scan', 'Кваліфікація незміненого генератора сіток на синтетичних ламаних (лише сітка, не траєкторії): '
                    'кількість пройдених сіток з кількості перевірених за станами',
          ['Стан'] + [f'S{s}' for s in states],
          [['пройшло / усього'] + [f'{cnt[s][0]}/{cnt[s][1]}' for s in states]],
          widths=[3.0] + [0.89] * len(states), size=8.5, align='l' + 'c' * len(states))
    fz_st = [r['outlook']['frozenMTS']['lastAdmissibleState'] for r in GEO['rows']]
    fz_d = [r['outlook']['frozenMTS']['lastTipToRingCircle_mm'][0] for r in GEO['rows']]
    sr_st = [r['outlook']['straight']['lastAdmissibleState'] for r in GEO['rows']]
    P('Другим можливим обмеженням є напрямна область радіусом 15 мм навколо вершини. Згідно з гіпотетичними '
      'продовженнями від S4 ([[tab:p_outlook]]), останніми станами, допустимими для напрямної, були б ' +
      f"S{min(fz_st)}–S{max(fz_st)} за замороженого кута МКН (вершина за {c(min(fz_d), 1)}–{c(max(fz_d), 1)} мм від кола "
      f"кільця 1) і S{min(sr_st)}–S{max(sr_st)} за прямого ходу (біля кільця 2). Це не прогнози: кут МКН надалі "
      'змінюється, а справжні траєкторії продовжувалися лише до S8. У межах кампанії напрямна жодного разу не '
      'зупиняла розрахунок.')
    rows = []
    for r in GEO['rows']:
        fz, sr = r['outlook']['frozenMTS'], r['outlook']['straight']
        ix = lambda o: 0 if o['objects'] == 'ring1' else 1
        rows.append([r['caseId'],
                     f"S{fz['lastAdmissibleState']}", c(fz['lastTipToRingCircle_mm'][ix(fz)], 3),
                     f"кільце {ix(fz) + 1}, `{fz['classification']}`",
                     f"S{sr['lastAdmissibleState']}", c(sr['lastTipToRingCircle_mm'][ix(sr)], 3),
                     f"кільце {ix(sr) + 1}, `{sr['classification']}`"])
    R.TAB('p_outlook', 'Гіпотетичні продовження від прийнятих станів S4 (не прогнози): останній стан, допустимий для '
                       '15-мм напрямної, відстань вершини до кола обмежувального кільця і клас обмеження',
          ['Конфігурація', 'Заморожений кут: стан', 'відстань, мм', 'кільце і клас', 'Прямий хід: стан',
           'відстань, мм', 'кільце і клас'], rows,
          widths=[2.6, 2.4, 1.7, 3.1, 1.7, 1.7, 3.3], size=8.5, align='lccclcl',
          note='Першою перевіркою, що спрацьовує в усіх восьми гіпотетичних продовженнях, є напрямна область '
               '(`HOLD_TIP_GUIDE`, `K9_tipGuideAdmissible`). Клас залежить від активності кільця: біля активного — '
               '`INTERFACE_APPROACH`, біля пасивного — числова перешкода `NUMERICAL_HOLD`.')
    P('Обидві межі слід розуміти правильно. Напрямна область 15 мм — запобіжник реалізації (охоронна умова '
      'нефізичної допоміжної грані), а не механічна величина. Так само 3,6 мм — найменша відстань від вершини до '
      'активної межі за чинного радіуса носія функції $q$ і запасу — є нижньою межею *чинного* алгоритму, а не '
      'фундаментальною довжиною механіки руйнування (рецензія 6055250219). Ні числове наближення до напрямної, ні '
      'зупинка біля пасивного контуру не є фізичною зупинкою тріщини.')

    # ------------------------------------------------------------------ 8.4
    H(2, 'Виконання кампанії і контроль якості', key='p_exec')
